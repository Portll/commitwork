if (isMainModule(import.meta.url)) {
  const args = process.argv.slice(2);
  const c = args.includes('--counts') || args.includes('--html') ? census() : null;
  const mmd = mermaid({ counts: c });
  const at = args.indexOf('--html');
  if (at >= 0) {
    const out = args[at + 1] || join(REPO, 'reports', 'verdict-flow.html');
    writeFileSync(out, html(mmd, c));
    console.log(out);
  } else {
    process.stdout.write(mmd);
  }
}
