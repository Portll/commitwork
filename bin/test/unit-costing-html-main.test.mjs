// Renders a markdown file into a self-contained HTML report file (bin/costing-html.mjs main).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { main } from '../costing-html.mjs';
import { mkdtempSync, rmSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const KEYS = ['CW_COSTING_SRC', 'CW_COSTING_OUT', 'CW_NOW', 'CW_COSTING_TILES'];

function withEnv(env, fn) {
  const saved = KEYS.map((k) => process.env[k]);
  const log = console.log;
  const lines = [];
  KEYS.forEach((k) => { delete process.env[k]; });
  Object.assign(process.env, env);
  console.log = (...a) => { lines.push(a.join(' ')); };
  try {
    return { value: fn(), lines };
  } finally {
    console.log = log;
    KEYS.forEach((k, n) => {
      if (saved[n] === undefined) delete process.env[k];
      else process.env[k] = saved[n];
    });
  }
}

function inTmp(fn) {
  const dir = mkdtempSync(join(tmpdir(), 'main-'));
  try {
    fn(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const titleOf = (html) => /\n<title>([^<]*)<\/title><style>/.exec(html)[1];
const tilesOf = (html) => html.slice(html.indexOf('<main>\n') + 7, html.indexOf('\n<nav class="toc">'));
const footerOf = (html) => /<div class="meta">(.*)\n/.exec(html)[1];
const logLine = (out, html, n) => `${out}  ${(html.length / 1024).toFixed(1)} KB  ${n} sections`;

test('returns 0, titles the page from the first level-one heading and logs size and section count', () => inTmp((dir) => {
  const src = join(dir, 'plan.md');
  const out = join(dir, 'plan.html');
  writeFileSync(src, 'Intro line.\n\n## Alpha\n\nOne.\n\n# Cost Plan\n\n## Beta\n\nTwo.\n');
  const { value, lines } = withEnv({ CW_COSTING_TILES: '' }, () => main(['node', 'cli', src, out]));
  const html = readFileSync(out, 'utf8');
  assert.equal(value, 0);
  assert.equal(titleOf(html), 'Cost Plan');
  assert.equal(tilesOf(html), '');
  assert.deepEqual(lines, [logLine(out, html, 2)]);
}));

test('falls back to the source file name when no line is a level-one heading', () => inTmp((dir) => {
  const src = join(dir, 'notes.md');
  const out = join(dir, 'notes.html');
  writeFileSync(src, '#NoSpace\n\n## Only\n\nText.\n');
  const { value, lines } = withEnv({}, () => main(['node', 'cli', src, out]));
  const html = readFileSync(out, 'utf8');
  assert.equal(value, 0);
  assert.equal(titleOf(html), 'notes.md');
  assert.deepEqual(lines, [logLine(out, html, 1)]);
}));

test('creates missing nested output directories before writing the page', () => inTmp((dir) => {
  const src = join(dir, 'doc.md');
  const out = join(dir, 'reports', 'deep', 'doc.html');
  writeFileSync(src, '# Nested\n\nBody.\n');
  const { value, lines } = withEnv({ CW_NOW: '2031-02-03' }, () => main(['node', 'cli', src, out]));
  const html = readFileSync(out, 'utf8');
  assert.equal(value, 0);
  assert.equal(html.slice(0, 15), '<!doctype html>');
  assert.equal(titleOf(html), 'Nested');
  assert.deepEqual(lines, [logLine(out, html, 0)]);
}));

test('stamps the footer with CW_NOW and falls back to today when CW_NOW is empty', () => inTmp((dir) => {
  const src = join(dir, 'doc.md');
  const out = join(dir, 'doc.html');
  writeFileSync(src, '# Stamp\n');
  const head = `Generated by <code>bin/costing-html.mjs</code> from <code>${src}</code> on `;
  withEnv({ CW_NOW: '2031-02-03' }, () => main(['node', 'cli', src, out]));
  assert.equal(footerOf(readFileSync(out, 'utf8')), `${head}2031-02-03.`);
  const today = new Date().toISOString().slice(0, 10);
  withEnv({ CW_NOW: '' }, () => main(['node', 'cli', src, out]));
  assert.equal(footerOf(readFileSync(out, 'utf8')), `${head}${today}.`);
}));

test('reads and writes the CW_COSTING_SRC and CW_COSTING_OUT paths instead of argv', () => inTmp((dir) => {
  const src = join(dir, 'env.md');
  const out = join(dir, 'env.html');
  writeFileSync(src, '# From Env\n');
  const argv = ['node', 'cli', join(dir, 'argv.md'), join(dir, 'argv.html')];
  const { value, lines } = withEnv({ CW_COSTING_SRC: src, CW_COSTING_OUT: out }, () => main(argv));
  const html = readFileSync(out, 'utf8');
  assert.equal(value, 0);
  assert.equal(titleOf(html), 'From Env');
  assert.equal(existsSync(argv[3]), false);
  assert.deepEqual(lines, [logLine(out, html, 0)]);
}));

test('renders tiles from CW_COSTING_TILES with emphasis only for literal true', () => inTmp((dir) => {
  const src = join(dir, 'doc.md');
  const out = join(dir, 'doc.html');
  const tiles = join(dir, 'tiles.json');
  writeFileSync(src, '# Tiles\n');
  writeFileSync(tiles, JSON.stringify([
    { value: '$1.2k', label: 'Monthly', emphasis: true },
    { value: '<5', label: 'Users', emphasis: 'yes' },
  ]));
  const { value } = withEnv({ CW_COSTING_TILES: tiles }, () => main(['node', 'cli', src, out]));
  assert.equal(value, 0);
  assert.equal(tilesOf(readFileSync(out, 'utf8')),
    '<div class="tiles"><div class="tile hi"><b>$1.2k</b><span>Monthly</span></div>'
    + '<div class="tile"><b>&lt;5</b><span>Users</span></div></div>');
}));

test('throws and writes nothing when the tiles file does not hold an array', () => inTmp((dir) => {
  const src = join(dir, 'doc.md');
  const out = join(dir, 'doc.html');
  const tiles = join(dir, 'tiles.json');
  writeFileSync(src, '# T\n');
  writeFileSync(tiles, '{"value":"1","label":"x"}');
  withEnv({ CW_COSTING_TILES: tiles }, () => assert.throws(() => main(['node', 'cli', src, out]), {
    name: 'Error',
    message: `costing-html: ${tiles} must hold an array of tiles`,
  }));
  assert.equal(existsSync(out), false);
}));

test('throws naming the index of a tile that lacks a string label', () => inTmp((dir) => {
  const src = join(dir, 'doc.md');
  const out = join(dir, 'doc.html');
  const tiles = join(dir, 'tiles.json');
  writeFileSync(src, '# T\n');
  writeFileSync(tiles, JSON.stringify([{ value: '1', label: 'ok' }, { value: '2' }]));
  withEnv({ CW_COSTING_TILES: tiles }, () => assert.throws(() => main(['node', 'cli', src, out]), {
    name: 'Error',
    message: `costing-html: tile 1 in ${tiles} needs a string value and label`,
  }));
  assert.equal(existsSync(out), false);
}));

test('throws ENOENT when the source markdown file is missing', () => inTmp((dir) => {
  const src = join(dir, 'missing.md');
  withEnv({}, () => assert.throws(() => main(['node', 'cli', src, join(dir, 'x.html')]), {
    name: 'Error',
    message: `ENOENT: no such file or directory, open '${resolve(src)}'`,
  }));
}));
