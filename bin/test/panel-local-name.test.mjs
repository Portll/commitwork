import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderInstall, renderUninstall, checkLocalName, ANCHOR, LABEL } from '../panel-local-name.mjs';

const CLI = join(dirname(fileURLToPath(import.meta.url)), '..', 'panel-local-name.mjs');
const TMP = mkdtempSync(join(tmpdir(), 'panel-local-name-'));
after(() => rmSync(TMP, { recursive: true, force: true }));

const run = (args, env = {}) => spawnSync(process.execPath, [CLI, ...args], { encoding: 'utf8', env: { ...process.env, ...env } });

test('the install script maps the name, redirects loopback :80 to the operator port, and loads at boot', () => {
  const s = renderInstall(7879);
  assert.match(s, /^#!\/bin\/sh\n# Generated by bin\/panel-local-name\.mjs\./);
  assert.match(s, /\[ "\$\(id -u\)" = 0 \] \|\| \{ echo "run this with sudo"/, 'it refuses to run without root rather than half-applying');
  assert.match(s, /\n127\.0\.0\.1 commitwork\.local\n::1 commitwork\.local\n/);
  assert.match(s, /rdr pass on lo0 inet proto tcp from any to 127\.0\.0\.1 port 80 -> 127\.0\.0\.1 port 7879\n/);
  assert.equal(ANCHOR, 'com.apple/250.net.portll.commitwork-local', 'a sub-anchor of the rdr-anchor /etc/pf.conf ships with');
  assert.match(s, /<string>\/sbin\/pfctl<\/string><string>-E<\/string><string>-a<\/string><string>com\.apple\/250\.net\.portll\.commitwork-local<\/string>/);
  assert.match(s, new RegExp(`launchctl bootstrap system /Library/LaunchDaemons/${LABEL.replaceAll('.', '\\.')}\\.plist`));
  assert.doesNotMatch(s, /\/etc\/pf\.conf\b(?! already)/, 'pf.conf itself is never written');
});

test('a re-run replaces the hosts block rather than appending a second', () => {
  const s = renderInstall(7879);
  const drop = s.indexOf("sed -i '' '/^# >>> commitwork.local /,/^# <<< commitwork.local$/d' /etc/hosts");
  assert.ok(drop > 0 && drop < s.indexOf('cat >> /etc/hosts'), 'the old block is removed before the new one is written');
});

test('the uninstall script removes every piece the install writes', () => {
  const u = renderUninstall();
  for (const piece of ["sed -i '' '/^# >>> commitwork.local ", `launchctl bootout system/${LABEL}`, `pfctl -a ${ANCHOR} -F all`,
    `/etc/pf.anchors/${LABEL}`, `/Library/LaunchDaemons/${LABEL}.plist`]) assert.ok(u.includes(piece), piece);
});

test('--write is deterministic, follows the operator port and writes where CW_PANEL_LOCAL_DIR says', () => {
  const env = { CW_PANEL_LOCAL_DIR: join(TMP, 'out'), CW_ADMIN_LOCAL_PORT: '9101' };
  assert.equal(run(['--write'], env).status, 0);
  const first = readFileSync(join(TMP, 'out', 'install.sh'), 'utf8');
  assert.equal(run(['--write'], env).status, 0);
  assert.equal(readFileSync(join(TMP, 'out', 'install.sh'), 'utf8'), first);
  assert.match(first, /port 80 -> 127\.0\.0\.1 port 9101\n/);
  assert.equal(run([]).status, 2, 'no mode is a usage error');
});

const loop = async () => [{ address: '127.0.0.1', family: 4 }, { address: '::1', family: 6 }];
const panel = async () => ({ status: 200, body: '{"token":"t"}' });

test('--check names the step where the chain from name to panel breaks', async () => {
  assert.equal(await checkLocalName({ lookup: loop, fetch: panel }), null);
  const nx = Object.assign(new Error('nx'), { code: 'ENOTFOUND' });
  assert.match(await checkLocalName({ lookup: async () => { throw nx; }, fetch: panel }), /does not resolve \(ENOTFOUND\): the hosts block is not installed/);
  assert.match(await checkLocalName({ lookup: async () => [{ address: '192.168.1.9' }], fetch: panel }), /resolves off loopback, to 192\.168\.1\.9/);
  const refused = Object.assign(new Error('r'), { code: 'ECONNREFUSED' });
  assert.match(await checkLocalName({ lookup: loop, fetch: async () => { throw refused; } }), /port 80 .* refused \(ECONNREFUSED\): the pf redirect is not loaded/);
  assert.match(await checkLocalName({ lookup: loop, fetch: async () => ({ status: 200, body: '<html>' }) }), /answered 200, but not as the panel/);
});
