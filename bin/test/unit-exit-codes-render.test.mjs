// Renders a markdown table of exit codes (bin/exit-codes.mjs render).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { render } from '../exit-codes.mjs';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

test('renders summary counts with mixed statuses', () => {
  const dir = mkdtempSync(join(tmpdir(), 'render-'));
  try {
    const input = {
      cli: [
        { name: 'commitwork scan', status: 'declared', source: 'bin/scan.mjs', via: 'header', entries: [{ code: 0, meaning: 'ok' }, { code: 20, meaning: 'stale' }] },
        { name: 'commitwork help', status: 'undeclared', source: 'bin/help.mjs', via: null, entries: [] }
      ],
      commands: [
        { name: 'bin/scan.mjs', status: 'prose', source: 'bin/scan.mjs', via: null, entries: [] },
        { name: 'bin/help.mjs', status: 'undeclared', source: 'bin/help.mjs', via: null, entries: [] }
      ]
    };
    const result = render(input);
    assert.equal(result, "# Exit codes\n\n<!-- Generated by bin/exit-codes.mjs \u2014 do not hand-edit; run `node bin/exit-codes.mjs` to refresh. -->\n\nEach table is what the command's header comment declares, read by `bin/exit-codes.mjs`. It is not\nverified against the code paths that set the exit status. `undeclared` means the header says\nnothing about exit status; `prose` means it does, in a shape the extractor does not tabulate.\nNeither is a claim about what the command returns. What may change between releases is in\n[STABILITY.md](STABILITY.md).\n\n4 commands: 1 declared, 1 prose, 2 undeclared. Of the declared, 0 use only codes 0\u201313, the range Node itself exits with (1 on an uncaught exception), and 1 declare a code of 20 or above.\n\n## `commitwork` subcommands\n\n### `commitwork scan`\n\nDeclared in `bin/scan.mjs` (`header`).\n\n| Exit | Meaning |\n|---:|---|\n| 0 | ok |\n| 20 | stale |\n\nUndeclared: `help`.\n\n## bin/\n\nProse only: `scan.mjs`.\n\nUndeclared: `help.mjs`.\n");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

