import { test, describe, after } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync, existsSync, mkdirSync, copyFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { houseCss, HOUSE_FACES } from '../../lib/house-css.mjs';
import { renderCopy, parseHeader, COPIES } from '../house-css.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CLI = join(REPO, 'bin', 'house-css.mjs');

const temps = [];
const temp = () => { const d = mkdtempSync(join(tmpdir(), 'house-css-copy-')); temps.push(d); return d; };
after(() => { for (const d of temps) rmSync(d, { recursive: true, force: true }); });

const run = (args, env = {}) => {
  const r = spawnSync(process.execPath, [CLI, ...args], { encoding: 'utf8', env: { ...process.env, CW_ADMIN_STATIC: '', CW_FONTS_DIR: '', ...env } });
  return { code: r.status, out: r.stdout, err: r.stderr };
};

const fakeFonts = (tag) => {
  const dir = temp();
  for (const f of HOUSE_FACES) writeFileSync(join(dir, f.file), `wOF2${tag}${f.file}`);
  return dir;
};

describe('admin/static/house.css', () => {
  test('is the served house sheet under its generated header, byte for byte', () => {
    const disk = readFileSync(join(REPO, 'admin', 'static', 'house.css'), 'utf8');
    const [header, ...rest] = disk.split('\n');
    assert.match(header, /^\/\* Generated by bin\/house-css\.mjs \(fonts=served\) from lib\/house-css\.mjs; .*never hand-edit\. \*\/$/);
    assert.equal(rest.join('\n'), `${houseCss({ fonts: 'served' })}\n`);
    assert.equal(disk, renderCopy({ fonts: 'served' }), 'stale: run node bin/house-css.mjs --write');
  });

  test('is a registered copy, and --check with no path finds every registered copy fresh', () => {
    assert.deepEqual(COPIES.find((c) => c.name === 'panel') && [COPIES[0].path(), COPIES[0].opts], [join(REPO, 'admin', 'static', 'house.css'), { fonts: 'served' }]);
    const r = run(['--check']);
    assert.equal(r.code, 0, r.err);
    assert.match(r.out, /^fresh +\S+admin\/static\/house\.css$/m);
    for (const c of COPIES) assert.match(r.out, new RegExp(`^fresh +${c.path().replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'm'), `${c.name} was not checked fresh`);
  });
});

describe('bin/house-css.mjs', () => {
  test('an .html copy is the house-css block alone: the page around it is untouched, and a page without one is refused', () => {
    const dir = temp();
    const page = join(dir, 'page.html');
    const outside = ['<!doctype html><head>', '</head><body><p>kept</p></body>'];
    writeFileSync(page, `${outside[0]}<style id="house-css">old</style><style>p{color:var(--ink)}</style>${outside[1]}`);
    assert.equal(run(['--write', page, '--fonts', 'none']).code, 0);
    const text = readFileSync(page, 'utf8');
    assert.ok(text.startsWith(`${outside[0]}<style id="house-css">${renderCopy({ fonts: 'none' })}</style><style>p{color:var(--ink)}</style>`));
    assert.ok(text.endsWith(outside[1]));
    assert.equal(run(['--check', page]).code, 0);
    writeFileSync(page, text.replace('--bg:', '--bg: '));
    assert.equal(run(['--check', page]).code, 1, 'a changed byte inside the block is stale');
    const bare = join(dir, 'bare.html');
    writeFileSync(bare, '<!doctype html><style>p{}</style>');
    assert.equal(run(['--write', bare]).code, 2, 'a page with no block has nowhere to hold the copy');
    assert.equal(readFileSync(bare, 'utf8'), '<!doctype html><style>p{}</style>', 'and is left as it was');
  });

  test('--write then --check is fresh; one changed byte is stale; a deleted copy is missing', () => {
    const path = join(temp(), 'nested', 'house.css');
    assert.equal(run(['--write', path]).code, 0);
    assert.equal(readFileSync(path, 'utf8'), renderCopy({ fonts: 'served' }));
    assert.equal(run(['--check', path]).code, 0);
    writeFileSync(path, readFileSync(path, 'utf8').replace('--bg:#f4f3ef', '--bg:#f4f3ee'));
    const stale = run(['--check', path]);
    assert.equal(stale.code, 1);
    assert.match(stale.out, /^stale +/m);
    rmSync(path);
    const missing = run(['--check', path]);
    assert.equal(missing.code, 1);
    assert.match(missing.out, /^missing /m);
  });

  test('a copy is regenerated with the options its header records', () => {
    const path = join(temp(), 'house.css');
    const fonts = fakeFonts('a');
    const w = run(['--write', path, '--fonts', 'inline', '--sans', '400,italic', '--mono', '400'], { CW_FONTS_DIR: fonts });
    assert.equal(w.code, 0, w.err);
    const text = readFileSync(path, 'utf8');
    assert.deepEqual(parseHeader(text), { fonts: 'inline', weights: { sans: [400, 'italic'], mono: [400] } });
    assert.equal((text.match(/@font-face/g) || []).length, 3);
    assert.equal(run(['--check', path], { CW_FONTS_DIR: fonts }).code, 0);
    assert.equal(run(['--check', path], { CW_FONTS_DIR: fakeFonts('b') }).code, 1, 'different face bytes must read as stale');
    assert.equal(run(['--check', path], { CW_FONTS_DIR: join(fonts, 'absent') }).code, 2, 'a face that cannot be read is not a verdict');
  });

  // fact: --write with no path writes every registered copy, so each is staged in a temp tree; the real pages are never rewritten
  const stagedTree = () => {
    const root = temp();
    for (const c of COPIES.filter((x) => x.name !== 'panel')) {
      const to = join(root, relative(REPO, c.path()));
      mkdirSync(dirname(to), { recursive: true });
      copyFileSync(c.path(), to);
    }
    return root;
  };

  test('the registered copies take their registered options, whatever a header claims', () => {
    const dir = temp();
    const root = stagedTree();
    assert.equal(run(['--write'], { CW_ADMIN_STATIC: dir, CW_HOUSE_CSS_ROOT: root, CW_WEB_ROOT: '' }).code, 0);
    assert.equal(readFileSync(join(dir, 'house.css'), 'utf8'), renderCopy({ fonts: 'served' }));
    assert.equal(run(['--check'], { CW_ADMIN_STATIC: dir, CW_HOUSE_CSS_ROOT: root, CW_WEB_ROOT: '' }).code, 0);
    writeFileSync(join(dir, 'house.css'), renderCopy({ fonts: 'none' }));
    assert.equal(run(['--check', join(dir, 'house.css')]).code, 0, 'fresh against its own header');
    assert.equal(run(['--check'], { CW_ADMIN_STATIC: dir, CW_HOUSE_CSS_ROOT: root, CW_WEB_ROOT: '' }).code, 1, 'stale against the registry');
  });

  test('a file with no header is refused rather than judged', () => {
    const path = join(temp(), 'house.css');
    writeFileSync(path, houseCss());
    const r = run(['--check', path]);
    assert.equal(r.code, 2);
    assert.match(r.err, /carries no bin\/house-css\.mjs header/);
  });

  test('writes are byte-identical across runs', () => {
    const a = join(temp(), 'a.css');
    const b = join(temp(), 'b.css');
    run(['--write', a]);
    run(['--write', b]);
    assert.equal(readFileSync(a, 'utf8'), readFileSync(b, 'utf8'));
  });

  test('usage errors exit 2 and write nothing', () => {
    const path = join(temp(), 'x.css');
    for (const args of [[], ['--write', path, '--fonts', 'cdn'], ['--write', path, '--sans', '300'], ['--write', path, '--serif', '400'],
      ['--write', '--fonts', 'none'], ['--check', path, '--fonts', 'none'], ['--write', '--check'], ['--write', path, 'b.css']]) {
      assert.equal(run(args).code, 2, args.join(' '));
    }
    assert.equal(existsSync(path), false);
    assert.equal(run(['--help']).code, 0);
  });
});
