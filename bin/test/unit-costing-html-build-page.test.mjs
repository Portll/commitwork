// Self-contained HTML costing page plus its h2 section count, from markdown and tiles (bin/costing-html.mjs buildPage).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildPage } from '../costing-html.mjs';

const HEAD = '<!doctype html><html lang="en"><head><meta charset="utf-8">';
const split = (page) => {
  const v = page.indexOf('<meta name="viewport"');
  return [page.slice(0, HEAD.length), page.slice(v, page.indexOf('<style>', v)), page.slice(page.lastIndexOf('</style>'))];
};
const view = (title) =>
  '<meta name="viewport" content="width=device-width,initial-scale=1">\n<title>' + title + '</title>';
const tail = (tiles, nav, html, src, stamp) =>
  '</style></head><body>\n<main>\n' + tiles + '\n<nav class="toc">' + nav + '</nav>\n' + html +
  '\n<div class="meta">Generated by <code>bin/costing-html.mjs</code> from <code>' + src + '</code> on ' + stamp +
  '.\nSelf-contained: no CDN, no external assets, safe over <code>file://</code>. Regenerate rather than hand-edit.</div>\n</main></body></html>';

test('a paragraph with tiles omitted gives an empty tile row, an empty toc and zero sections', () => {
  const r = buildPage({ md: 'hello', title: 'T', stamp: '2024-01-01', src: 's.md' });
  assert.deepEqual(Object.keys(r), ['page', 'sections']);
  assert.equal(r.sections, 0);
  assert.deepEqual(split(r.page), [HEAD, view('T'), tail('', '', '<p>hello</p>', 's.md', '2024-01-01')]);
});

test('empty markdown and an empty tiles array leave the body between toc and meta empty', () => {
  const r = buildPage({ md: '', title: 'Empty', stamp: '2025-06-30', src: 'e.md', tiles: [] });
  assert.equal(r.sections, 0);
  assert.deepEqual(split(r.page), [HEAD, view('Empty'), tail('', '', '', 'e.md', '2025-06-30')]);
});

test('one tile without emphasis renders a plain tile inside the tiles row', () => {
  const tiles = [{ value: 'v1', label: 'l1', emphasis: false }];
  const r = buildPage({ md: 'x', title: 'T', stamp: '2024-01-01', src: 's.md', tiles });
  assert.equal(r.sections, 0);
  assert.deepEqual(split(r.page), [HEAD, view('T'), tail(
    '<div class="tiles"><div class="tile"><b>v1</b><span>l1</span></div></div>',
    '', '<p>x</p>', 's.md', '2024-01-01')]);
});

test('an emphasised tile gets the hi class and tile text, title and src are html-escaped', () => {
  const tiles = [{ value: '7', label: 'days' }, { value: '<5', label: 'a>b', emphasis: true }];
  const r = buildPage({ md: 'x', title: 'Tiers <v2>', stamp: '2026-10-30', src: 'c<1>.md', tiles });
  assert.equal(r.sections, 0);
  assert.deepEqual(split(r.page), [HEAD, view('Tiers &lt;v2&gt;'), tail(
    '<div class="tiles"><div class="tile"><b>7</b><span>days</span></div>'
      + '<div class="tile hi"><b>&lt;5</b><span>a&gt;b</span></div></div>',
    '', '<p>x</p>', 'c&lt;1&gt;.md', '2026-10-30')]);
});

test('each level-two heading becomes a toc link and counts as a section', () => {
  const r = buildPage({ md: '## First\n\n## Second', title: 'T', stamp: '2024-01-01', src: 's.md', tiles: [] });
  assert.equal(r.sections, 2);
  assert.deepEqual(split(r.page), [HEAD, view('T'), tail(
    '', '<a href="#first">First</a><a href="#second">Second</a>',
    '<h2 id="first">First</h2>\n<h2 id="second">Second</h2>', 's.md', '2024-01-01')]);
});

test('level one and three headings render but stay out of the toc', () => {
  const r = buildPage({ md: '# Top\n### Deep\n## Mid Part', title: 'T', stamp: '2024-01-01', src: 's.md' });
  assert.equal(r.sections, 1);
  assert.deepEqual(split(r.page), [HEAD, view('T'), tail(
    '', '<a href="#mid-part">Mid Part</a>',
    '<h1 id="top">Top</h1>\n<h3 id="deep">Deep</h3>\n<h2 id="mid-part">Mid Part</h2>', 's.md', '2024-01-01')]);
});

test('inline markup in a section heading is rendered in the toc link alongside a tile row', () => {
  const tiles = [{ value: '3', label: 'tiers', emphasis: true }];
  const r = buildPage({ md: '## Use `x` **now**\nbody text', title: 'T', stamp: '2024-02-29', src: 'k.md', tiles });
  assert.equal(r.sections, 1);
  assert.deepEqual(split(r.page), [HEAD, view('T'), tail(
    '<div class="tiles"><div class="tile hi"><b>3</b><span>tiers</span></div></div>',
    '<a href="#use-x-now">Use <code>x</code> <strong>now</strong></a>',
    '<h2 id="use-x-now">Use <code>x</code> <strong>now</strong></h2>\n<p>body text</p>', 'k.md', '2024-02-29')]);
});
