// bin/manifest-map.mjs as a process. Its outputs are fixed relative to the script
// (manifests/<name>.map.json, docs/MANIFEST-MAP.md) with no env override, so the write path is
// exercised on a verbatim copy of the script (and its two leaf imports) in a scratch root — never by
// writing into this checkout. Pins: line numbers read from the raw text, group membership as the
// union of the top-level map and each check's own tag, the tool/trigger indexes, byte-identical
// reruns, and --check: 0 when current, 3 when absent or stale, writing nothing either way.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, copyFileSync, readFileSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const CW = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SCRIPT = join(CW, 'bin', 'manifest-map.mjs');

// Line numbers are the point of the index, so the fixture is laid out by hand.
const MANIFEST = `{
  "groups": { "quick": ["lint-a"] },
  "checks": [
    {
      "id": "lint-a",
      "description": "a linter",
      "requires": { "tools": ["toolz"] },
      "appliesIfExists": ["package.json"],
      "report": { "format": "sarif" },
      "timeoutSec": 60
    },
    {
      "id": "secrets-b",
      "groups": ["quick", "deep"],
      "requires": { "tools": ["toolz", "leakfinder"], "docker": true }
    },
    {
      "id": "go-c",
      "appliesIfSourceExt": [".go"],
      "requiresUrl": true,
      "nested": { "id": "lint-a" }
    }
  ]
}
`;

/** A scratch root holding a verbatim copy of the script and its leaf imports. */
function relocated(t) {
  const root = mkdtempSync(join(tmpdir(), 'cw-manifest-map-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  for (const rel of ['bin/manifest-map.mjs', 'lib/is-main.mjs', 'monitor/lockfile.mjs']) {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    copyFileSync(join(CW, rel), join(root, rel));
  }
  mkdirSync(join(root, 'manifests'));
  writeFileSync(join(root, 'manifests', 'fixture.json'), MANIFEST);
  return { root, json: join(root, 'manifests', 'fixture.map.json'), md: join(root, 'docs', 'MANIFEST-MAP.md') };
}

const run = (script, args, cwd) => {
  const r = spawnSync(process.execPath, [script, ...args], { encoding: 'utf8', cwd });
  return { code: r.status, out: r.stdout, err: r.stderr };
};

test('the write run indexes every check by its raw line, groups by the union of both declarations', (t) => {
  const s = relocated(t);
  const r = run(join(s.root, 'bin', 'manifest-map.mjs'), ['fixture'], s.root);
  assert.equal(r.code, 0, r.err);
  assert.match(r.out, /manifest-map: 3 checks · 2 groups · 2 tools · 2 triggers/);
  const map = JSON.parse(readFileSync(s.json, 'utf8'));
  assert.equal(map.manifest, 'fixture');
  assert.equal(map.manifestLines, 25);
  assert.deepEqual(Object.fromEntries(Object.entries(map.byId).map(([id, c]) => [id, c.line])), { 'go-c': 18, 'lint-a': 5, 'secrets-b': 13 });
  assert.deepEqual(map.byGroup, { deep: ['secrets-b'], quick: ['lint-a', 'secrets-b'] });
  assert.deepEqual(map.byTool, { leakfinder: ['secrets-b'], toolz: ['lint-a', 'secrets-b'] });
  assert.deepEqual(map.byTrigger, { '.go': ['go-c'], 'package.json': ['lint-a'] });
  assert.deepEqual(map.byId['secrets-b'], { line: 13, description: null, groups: ['deep', 'quick'], tools: ['leakfinder', 'toolz'],
    docker: true, appliesIfExists: [], appliesIfSourceExt: [], appliesIfGit: false, requiresUrl: false, report: null, timeoutSec: null, universal: true });
  assert.equal(map.byId['lint-a'].universal, false);
  assert.equal(map.byId['go-c'].requiresUrl, true);

  const md = readFileSync(s.md, 'utf8');
  assert.match(md, /<!-- Generated by bin\/manifest-map\.mjs — do not hand-edit; re-run to refresh\. -->/);
  assert.match(md, /- \*\*`quick`\*\* \(2\)\n {2}- `lint-a` — L5 · package\.json\n {2}- `secrets-b` — L13 · _universal_/);
  assert.match(md, /\| `toolz` \| 2 \| `lint-a`, `secrets-b` \|/);
  assert.match(md, /\| 18 \| `go-c` \| {2}\(\+url\) \| \.go \| {2}\| {2}\|/);
});

test('--check is 0 on current outputs, 3 once the manifest moves, and never writes', (t) => {
  const s = relocated(t);
  const script = join(s.root, 'bin', 'manifest-map.mjs');
  assert.equal(run(script, ['fixture'], s.root).code, 0);
  const json0 = readFileSync(s.json, 'utf8');
  const md0 = readFileSync(s.md, 'utf8');

  const current = run(script, ['fixture', '--check'], s.root);
  assert.equal(current.code, 0, current.err);
  assert.equal(current.out.trim(), 'manifest-map: current (3 checks)');

  // timeoutSec is in the JSON and not the markdown: only the file that carries it is stale
  writeFileSync(join(s.root, 'manifests', 'fixture.json'), MANIFEST.replace('"timeoutSec": 60', '"timeoutSec": 90'));
  const one = run(script, ['fixture', '--check'], s.root);
  assert.equal(one.code, 3);
  assert.match(one.err, /manifest-map: STALE — \S*fixture\.map\.json\n/);
  assert.doesNotMatch(one.err, /MANIFEST-MAP\.md/);

  writeFileSync(join(s.root, 'manifests', 'fixture.json'), MANIFEST.replace('"tools": ["toolz"]', '"tools": ["toolz", "lintkit"]'));
  const stale = run(script, ['fixture', '--check'], s.root);
  assert.equal(stale.code, 3);
  assert.match(stale.err, /manifest-map: STALE — .*fixture\.map\.json, .*MANIFEST-MAP\.md/);
  assert.equal(readFileSync(s.json, 'utf8'), json0, '--check rewrote the json');
  assert.equal(readFileSync(s.md, 'utf8'), md0, '--check rewrote the markdown');
});

test('a rerun on an unchanged manifest rewrites byte-identical JSON; only the markdown stamp moves', (t) => {
  const s = relocated(t);
  const script = join(s.root, 'bin', 'manifest-map.mjs');
  assert.equal(run(script, ['fixture'], s.root).code, 0);
  const json0 = readFileSync(s.json, 'utf8');
  const md0 = readFileSync(s.md, 'utf8');
  assert.equal(run(script, ['fixture'], s.root).code, 0);
  assert.equal(readFileSync(s.json, 'utf8'), json0);
  const strip = (m) => m.replace(/^Generated \d{4}-.*$/m, 'Generated <at>');
  assert.equal(strip(readFileSync(s.md, 'utf8')), strip(md0));
});

test('--check with no outputs yet is stale and names them absent', (t) => {
  const s = relocated(t);
  const r = run(join(s.root, 'bin', 'manifest-map.mjs'), ['fixture', '--check'], s.root);
  assert.equal(r.code, 3);
  assert.match(r.err, /STALE — .*fixture\.map\.json \(absent\), .*MANIFEST-MAP\.md \(absent\)/);
  assert.equal(existsSync(s.json), false);
});

test('the in-place script refuses a manifest path that does not exist', (t) => {
  const dir = mkdtempSync(join(tmpdir(), 'cw-manifest-map-missing-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const r = run(SCRIPT, [join(dir, 'nope.json'), '--check'], dir);
  assert.notEqual(r.code, 0);
  assert.match(r.err, /manifest not found: .*nope\.json/);
});

test('a description holding a backslash before a pipe stays in its own table cell', async () => {
  const { renderMarkdown } = await import('../manifest-map.mjs');
  const check = { line: 7, description: 'reads C:\\x\\|y', groups: [], tools: ['t'], docker: false, appliesIfExists: [], appliesIfSourceExt: [], requiresUrl: false, report: null, universal: true };
  const md = renderMarkdown({ manifest: 'm', manifestLines: 9, checkCount: 1, byGroup: {}, byTrigger: {}, byTool: {}, byId: { c: check } }, { at: 'x' });
  const row = md.split('\n').find((l) => l.startsWith('| 7 |'));
  // GFM splits on every pipe a backslash does not consume; a backslash consumes the next character.
  const cells = row.slice(1, -1).match(/(?:\\.|[^|\\])+/g);
  assert.equal(cells.length, 6, `the description split the row: ${row}`);
  assert.equal(cells[5].trim().replace(/\\(.)/g, '$1'), 'reads C:\\x\\|y');
});
