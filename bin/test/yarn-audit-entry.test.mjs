// bin/yarn-audit.mjs as a process with fetch replaced by a preload (--import), so the advisory
// endpoint is never reached: the stub records each request body and answers with canned advisories
// or an HTTP failure. Pins: the payload is exactly the versions yarn.lock pins (scoped names,
// multi-range headers, two versions of one package), chunked at 400; the report is npm-audit v2
// with the worst severity per package, isDirect from root AND workspace manifests, and the pinned
// range; --out and CW_REPORT_DIR choose the file; no lock, a berry lock and a failing endpoint are
// each an error that writes no report.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const CW = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CLI = join(CW, 'bin', 'yarn-audit.mjs');
const BULK = 'https://registry.npmjs.org/-/npm/v1/security/advisories/bulk';

const STUB = `import { appendFileSync } from 'node:fs';
globalThis.fetch = async (url, init = {}) => {
  appendFileSync(process.env.FAKE_FETCH_LOG, JSON.stringify({ url: String(url), method: init.method, body: JSON.parse(init.body) }) + '\\n');
  if (process.env.FAKE_FETCH_FAIL) return { ok: false, status: 503, statusText: 'Service Unavailable', json: async () => ({}) };
  return { ok: true, status: 200, json: async () => JSON.parse(process.env.FAKE_ADVISORIES || '{}') };
};
`;

const LOCK = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@example/ui@^1.0.0", "@example/ui@^1.1.0":
  version "1.2.3"
  resolved "https://registry.yarnpkg.com/@example/ui/-/ui-1.2.3.tgz"

lodash@^4.17.0:
  version "4.17.20"

minimist@^1.2.0, minimist@~1.2.5:
  version "1.2.5"

minimist@^0.0.8:
  version "0.0.8"
`;

const ADVISORIES = {
  lodash: [{ id: 1001, title: 'Prototype pollution', severity: 'high', url: 'https://example.invalid/a/1001',
    vulnerable_versions: '<4.17.21', cwe: ['CWE-1321'], cvss: { score: 7.4, vectorString: 'CVSS:3.1/AV:N' } }],
  minimist: [{ id: 1002, title: 'Pollution A', severity: 'moderate' }, { id: 1003, title: 'Pollution B', severity: 'critical' }],
  '@example/ui': [],
};

function sandbox(t, { lock = LOCK, workspaces = true } = {}) {
  const dir = mkdtempSync(join(tmpdir(), 'cw-yarn-audit-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const repo = join(dir, 'repo'); mkdirSync(repo);
  if (lock !== null) writeFileSync(join(repo, 'yarn.lock'), lock);
  writeFileSync(join(repo, 'package.json'), JSON.stringify({ name: 'root', dependencies: { lodash: '^4.17.0' },
    ...(workspaces ? { workspaces: ['packages/*'] } : {}) }));
  mkdirSync(join(repo, 'packages', 'app'), { recursive: true });
  writeFileSync(join(repo, 'packages', 'app', 'package.json'), JSON.stringify({ name: 'app', devDependencies: { minimist: '^1.2.0' } }));
  const stub = join(dir, 'fake-fetch.mjs'); writeFileSync(stub, STUB);
  return { dir, repo, stub, log: join(dir, 'fetch.jsonl'), out: join(dir, 'npm-audit.json') };
}

function run(s, args, env = {}) {
  const r = spawnSync(process.execPath, ['--import', pathToFileURL(s.stub).href, CLI, ...args], { encoding: 'utf8',
    cwd: s.dir, env: { ...process.env, FAKE_FETCH_LOG: s.log, FAKE_ADVISORIES: JSON.stringify(ADVISORIES), ...env } });
  return { code: r.status, out: r.stdout, err: r.stderr };
}
const calls = (s) => (existsSync(s.log) ? readFileSync(s.log, 'utf8').trim().split('\n').map((l) => JSON.parse(l)) : []);

test('the request is exactly the pinned versions, and the report is npm-audit v2 with the worst severity per package', (t) => {
  const s = sandbox(t);
  const r = run(s, [s.repo, '--out', s.out]);
  assert.equal(r.code, 0, r.err);
  const [call, ...more] = calls(s);
  assert.equal(more.length, 0);
  assert.equal(call.url, BULK);
  assert.equal(call.method, 'POST');
  assert.deepEqual(call.body, { '@example/ui': ['1.2.3'], lodash: ['4.17.20'], minimist: ['0.0.8', '1.2.5'] });

  const rep = JSON.parse(readFileSync(s.out, 'utf8'));
  assert.equal(rep.auditReportVersion, 2);
  assert.deepEqual(Object.keys(rep.vulnerabilities).sort(), ['lodash', 'minimist'], 'an empty advisory list is not a vulnerability');
  const lo = rep.vulnerabilities.lodash;
  assert.deepEqual([lo.severity, lo.isDirect, lo.range, lo.fixAvailable], ['high', true, '4.17.20', false]);
  assert.deepEqual(lo.via[0], { source: 1001, name: 'lodash', dependency: 'lodash', title: 'Prototype pollution',
    url: 'https://example.invalid/a/1001', severity: 'high', cwe: ['CWE-1321'], cvss: { score: 7.4, vectorString: 'CVSS:3.1/AV:N' }, range: '<4.17.21' });
  const mm = rep.vulnerabilities.minimist;
  assert.equal(mm.severity, 'critical', 'the worst of moderate and critical');
  assert.equal(mm.isDirect, true, 'declared only by a workspace package');
  assert.equal(mm.range, '1.2.5 || 0.0.8');
  assert.deepEqual(rep.metadata.vulnerabilities, { info: 0, low: 0, moderate: 0, high: 1, critical: 1, total: 2 });
  assert.equal(rep.metadata.dependencies.total, 3);
  assert.equal(r.err.trim(), `yarn-audit: 3 locked packages, 2 vulnerable (crit 1, high 1, moderate 0, low 0) -> ${s.out}`);
});

test('without workspaces a workspace-only dependency is not direct; with no --out the report goes to CW_REPORT_DIR', (t) => {
  const s = sandbox(t, { workspaces: false });
  const reports = join(s.dir, 'reports'); mkdirSync(reports);
  const r = run(s, [s.repo], { CW_REPORT_DIR: reports });
  assert.equal(r.code, 0, r.err);
  const rep = JSON.parse(readFileSync(join(reports, 'npm-audit.json'), 'utf8'));
  assert.equal(rep.vulnerabilities.minimist.isDirect, false);
  assert.equal(rep.vulnerabilities.lodash.isDirect, true);
});

test('more than 400 pinned packages are sent in 400-package chunks and merged', (t) => {
  const lock = ['# yarn lockfile v1', ''].concat(Array.from({ length: 401 }, (_, i) => `pkg-${String(i).padStart(3, '0')}@^1.0.0:\n  version "1.0.${i}"\n`)).join('\n');
  const s = sandbox(t, { lock });
  const r = run(s, [s.repo, '--out', s.out], { FAKE_ADVISORIES: JSON.stringify({}) });
  assert.equal(r.code, 0, r.err);
  assert.deepEqual(calls(s).map((c) => Object.keys(c.body).length), [400, 1]);
  assert.match(r.err, /401 locked packages, 0 vulnerable/);
});

test('no yarn.lock is exit 2, with no request and no report', (t) => {
  const s = sandbox(t, { lock: null });
  const r = run(s, [s.repo, '--out', s.out]);
  assert.equal(r.code, 2);
  assert.match(r.err, /yarn-audit: no yarn\.lock at .*repo\/yarn\.lock/);
  assert.deepEqual(calls(s), []);
  assert.equal(existsSync(s.out), false);
});

test('a berry lockfile parses to zero packages and is an error, never a clean report', (t) => {
  const s = sandbox(t, { lock: '__metadata:\n  version: 6\n  cacheKey: 8\n\n"lodash@npm:^4.17.0":\n  version: 4.17.21\n  resolution: "lodash@npm:4.17.21"\n' });
  const r = run(s, [s.repo, '--out', s.out]);
  assert.equal(r.code, 2);
  assert.match(r.err, /parsed 0 packages \(yarn berry\/v2 lockfiles are not supported\)/);
  assert.deepEqual(calls(s), []);
  assert.equal(existsSync(s.out), false);
});

test('a failing advisory endpoint is exit 1 naming the status, and no report is written', (t) => {
  const s = sandbox(t);
  const r = run(s, [s.repo, '--out', s.out], { FAKE_FETCH_FAIL: '1' });
  assert.equal(r.code, 1);
  assert.equal(r.err.trim(), 'yarn-audit: advisory endpoint 503 Service Unavailable');
  assert.equal(existsSync(s.out), false);
});
