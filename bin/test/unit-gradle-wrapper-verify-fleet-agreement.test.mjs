// Computes cross-repo agreement of gradle wrapper artifact hashes per declared version (bin/gradle-wrapper-verify.mjs fleetAgreement).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { fleetAgreement } from '../gradle-wrapper-verify.mjs';

test('returns gradle-wrapper.jar label for default artifact', () => {
  const r = fleetAgreement([]);
  assert.equal(r.artifact, "gradle-wrapper.jar");
});

test('returns gradlew label for gradlewSha256 artifact', () => {
  const r = fleetAgreement([], { artifact: 'gradlewSha256' });
  assert.equal(r.artifact, "gradlew");
});

test('skips null results without throwing', () => {
  const r = fleetAgreement([null]);
  assert.equal(r.versionsCompared, 0);
});

test('skips results with applicable false', () => {
  const r = fleetAgreement([{ applicable: false, declaredVersion: '8.0', jarSha256: 'a' }]);
  assert.equal(r.versionsCompared, 0);
});

test('skips results missing declaredVersion', () => {
  const r = fleetAgreement([{ applicable: true, jarSha256: 'a' }]);
  assert.equal(r.versionsCompared, 0);
});

test('skips results missing artifact hash', () => {
  const r = fleetAgreement([{ applicable: true, declaredVersion: '8.0' }]);
  assert.equal(r.versionsCompared, 0);
});

test('reports singleton when only one repo declares a version', () => {
  const r = fleetAgreement([{ applicable: true, declaredVersion: '8.0', jarSha256: 'a', repo: 'r1' }]);
  assert.deepEqual(r.unexaminable, [{ version: "8.0", repos: ["r1"] }]);
});

test('reports singleton when two repos share the same hash', () => {
  const r = fleetAgreement([
    { applicable: true, declaredVersion: '8.0', jarSha256: 'a', repo: 'r1' },
    { applicable: true, declaredVersion: '8.0', jarSha256: 'a', repo: 'r2' }
  ]);
  assert.deepEqual(r.unexaminable, []);
});

test('reports disagreement when two repos have different hashes', () => {
  const r = fleetAgreement([
    { applicable: true, declaredVersion: '8.0', jarSha256: 'a', repo: 'r1' },
    { applicable: true, declaredVersion: '8.0', jarSha256: 'b', repo: 'r2' }
  ]);
  assert.deepEqual(r.disagreements, [{ artifact: "gradle-wrapper.jar", version: "8.0", groups: [{ sha: "a", repos: ["r1"], n: 1 }, { sha: "b", repos: ["r2"], n: 1 }], note: "2 distinct gradle-wrapper.jar hashes across repos all declaring gradle 8.0. It is generated by Gradle, not authored by the project, so they should match. A project that regenerated with a different Gradle than its distributionUrl claims produces this harmlessly \u2014 and so does a substituted one." }]);
});

test('reports disagreement with three repos and two distinct hashes', () => {
  const r = fleetAgreement([
    { applicable: true, declaredVersion: '8.0', jarSha256: 'a', repo: 'r1' },
    { applicable: true, declaredVersion: '8.0', jarSha256: 'a', repo: 'r2' },
    { applicable: true, declaredVersion: '8.0', jarSha256: 'b', repo: 'r3' }
  ]);
  assert.deepEqual(r.disagreements, [{ artifact: "gradle-wrapper.jar", version: "8.0", groups: [{ sha: "a", repos: ["r1", "r2"], n: 2 }, { sha: "b", repos: ["r3"], n: 1 }], note: "2 distinct gradle-wrapper.jar hashes across repos all declaring gradle 8.0. It is generated by Gradle, not authored by the project, so they should match. A project that regenerated with a different Gradle than its distributionUrl claims produces this harmlessly \u2014 and so does a substituted one." }]);
});
