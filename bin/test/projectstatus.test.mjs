// projectstatus: the status page must not lie either. Pins: determinism under CW_NOW, "not
// scanned" for an area with no rollup, rollup age travelling with the counts, self-contained
// html, and the md declaring its generator.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, mkdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { gather, renderMarkdown, renderHtml, releaseSafeLabel, releaseNameRules } from '../projectstatus.mjs';
import { redactionMapPathFor } from '../../monitor/store-paths.mjs';

// The release-name manifest resolves from this root, or from CW_REDACTION_MAP.
const repoRootForRules = () => resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

const NOW = new Date('2026-07-29T12:00:00Z');

function fixtureRoot() {
  const root = mkdtempSync(join(tmpdir(), 'projectstatus-'));
  writeFileSync(join(root, 'README.md'),
    '<!-- verified-against: 2026-07-29 -->\n# fixture\n\n## Documentation\n\n- [m](mod/README.md)\n');
  mkdirSync(join(root, 'mod'), { recursive: true });
  writeFileSync(join(root, 'mod/README.md'), '<!-- verified-against: 2026-07-29 -->\n# mod\n');
  mkdirSync(join(root, 'monitor', 'private'), { recursive: true });
  // The map is REQUIRED, not optional: absence makes releaseNameRules refuse, because a publisher
  // that cannot read the map cannot tell whether it is about to disclose a client. A fixture without
  // one is an incomplete fixture, not a reason to make the code lenient.
  writeFileSync(join(root, 'monitor/private/release-redactions.json'), JSON.stringify({
    names: [{ name: 'private-product', replacement: 'client-a', scope: 'all', why: 'fixture' }],
  }));
  writeFileSync(join(root, 'monitor/private/projects.json'), JSON.stringify({
    reportsRoot: 'reports',
    areas: [
      { slug: 'alpha', label: 'Alpha', out: 'alpha-out' },
      { slug: 'ghost', label: 'Ghost' /* no rollup on disk */, out: 'ghost' },
    ],
  }));
  mkdirSync(join(root, 'reports/alpha-out'), { recursive: true });
  writeFileSync(join(root, 'reports/alpha-out/rollup.json'), JSON.stringify({
    generated: '2026-07-28T12:00:00Z',
    openTotals: { crit: 1, high: 2, med: 3, low: 4 },
    scanned: { repos: 2 },
    freshness: { stateAtWrite: 'fresh' },
  }));
  return root;
}

test('deterministic: same inputs and CW_NOW give byte-identical outputs', () => {
  const root = fixtureRoot();
  const a = gather({ root, now: NOW });
  const b = gather({ root, now: NOW });
  assert.equal(renderMarkdown(a), renderMarkdown(b));
  assert.equal(renderHtml(a), renderHtml(b));
});

test('area without a rollup is "not scanned", never clean; rollup rows carry age', () => {
  const s = gather({ root: fixtureRoot(), now: NOW });
  const ghost = s.fleet.find((a) => a.slug === 'ghost');
  assert.equal(ghost.scanned, false);
  const md = renderMarkdown(s);
  assert.match(md, /Ghost \| — \| \*\*not scanned\*\*/);
  assert.match(md, /24h ago/); // alpha rollup generated 24h before CW_NOW
  assert.match(md, /crit 1 · high 2 · med 3 · low 4/);
});

test('html is self-contained with one-click PDF; md declares its generator', () => {
  const s = gather({ root: fixtureRoot(), now: NOW });
  const html = renderHtml(s);
  assert.match(html, /window\.print\(\)/);
  assert.match(html, /Download PDF/);
  assert.doesNotMatch(html, /https?:\/\//); // no external assets — file:// safe
  const md = renderMarkdown(s);
  assert.match(md, /Generated by bin\/projectstatus\.mjs/);
});

test('fleet labels use the release-name mapping, so regeneration cannot restore private names', () => {
  const rules = [{ pattern: /private-product/gi, replacement: 'client-a' }];
  assert.equal(releaseSafeLabel('Private-Product (Go)', rules), 'client-a (Go)');
});

// The rules are applied by REDUCTION, so whichever pattern runs first wins an overlap. In manifest
// order a stem runs before every compound built on it and eats the stem, leaving a token the
// manifest never declared. Measured 2026-09-07 before the fix: six of six compound names came out
// wrong — `clientA-monorepo` -> `clientA-monorepo` where the manifest declares `clientA`.
// It is not a disclosure, which is exactly why it survived: the client is redacted either way and
// the output looks right.
//
// The real manifest is private and absent from a clone, so the property is proved on a synthetic one
// everywhere and on the real one wherever it is present. The synthetic one is written stem-first —
// the order an unsorted reduction gets wrong — with aliases that share their stem's replacement.
const STEM_FIRST = [
  { name: 'acmefixture', replacement: 'clientZ', scope: 'all', why: 'fixture stem' },
  { name: 'acmefixture-buildout', replacement: 'clientZ', scope: 'all', why: 'fixture alias' },
  { name: 'AcmeFixtureLtd', replacement: 'clientZ', scope: 'all', why: 'fixture alias' },
  { name: 'examplefixture', replacement: 'internalZ', scope: 'all', why: 'fixture stem' },
  { name: 'examplefixture-dev', replacement: 'internalZ-dev', scope: 'all', why: 'fixture compound' },
];

/** releaseNameRules over the synthetic manifest, through the override the real one honours. */
function fixtureRules() {
  const path = join(mkdtempSync(join(tmpdir(), 'projectstatus-rules-')), 'release-redactions.json');
  writeFileSync(path, JSON.stringify({ names: STEM_FIRST }));
  const was = process.env.CW_REDACTION_MAP;
  process.env.CW_REDACTION_MAP = path;
  try { return releaseNameRules(repoRootForRules()); }
  finally { if (was === undefined) delete process.env.CW_REDACTION_MAP; else process.env.CW_REDACTION_MAP = was; }
}

const wrongLabels = (declared, rules) => declared
  .map((n) => ({ name: n.name, want: n.replacement, got: releaseSafeLabel(n.name, rules) }))
  .filter((r) => r.got !== r.want);

test('a stem does not consume the compound name built on it', () => {
  // nosemgrep: javascript.lang.security.audit.detect-non-literal-regexp.detect-non-literal-regexp -- test helper building a pattern from a literal or escaped value defined in the test
  const inManifestOrder = STEM_FIRST.map(({ name, replacement }) => ({ pattern: new RegExp(name, 'gi'), replacement }));
  assert.notDeepEqual(wrongLabels(STEM_FIRST, inManifestOrder), [],
    'precondition: reduced in manifest order the fixture must come out wrong, or this proves nothing');
  assert.deepEqual(wrongLabels(STEM_FIRST, fixtureRules()), [],
    'every declared name must map to its OWN replacement; a leftover suffix means a stem rule ran first');
});

const liveManifest = () => redactionMapPathFor(repoRootForRules());
const needsLiveManifest = () => {
  try { statSync(liveManifest()); return {}; } catch (e) {
    if (e.code !== 'ENOENT') throw e;
    return { skip: `private release-redaction manifest absent at ${liveManifest()} (ENOENT) — a public checkout cannot check the real names` };
  }
};

test('the real manifest: no stem consumes a compound name built on it', needsLiveManifest(), () => {
  const declared = JSON.parse(readFileSync(liveManifest(), 'utf8')).names;
  assert.deepEqual(wrongLabels(declared, releaseNameRules(repoRootForRules())), [],
    'every declared name must map to its OWN replacement; a leftover suffix means a stem rule ran first');
});

test('the rule order that guarantees it is asserted, not incidental', () => {
  const rules = fixtureRules();
  // Longest first. Without this the guarantee above holds only while the manifest happens to be
  // ordered favourably, which is a streak rather than a property.
  const lengths = rules.map((r) => r.pattern.source.replace(/\\/g, '').length);
  assert.deepEqual(lengths, [...lengths].sort((a, b) => b - a),
    'release-name rules must be sorted longest-name-first before they are reduced over');
});

