// ── issue tracker section (explicit uncertainty at the issue-store level too) ──────────────────────────

function issueFixture(id, over = {}) {
  return {
    id, area: 'alpha', repo: null, source: { kind: 'manual', key: null, tool: null, rule: null },
    kind: 'task', severity: 'med', title: `fixture ${id}`, state: 'open', closedAs: null,
    deps: { blockedBy: [], duplicateOf: null, supersededBy: null }, claim: null, attemptCount: 0,
    suspect: false, evidence: [], waiver: null, authorityRequired: false,
    slaDueAt: '2026-09-01T00:00:00Z', reopenCount: 0,
    createdAt: '2026-07-01T00:00:00Z', updatedAt: '2026-07-01T00:00:00Z',
    ...over,
  };
}

test('absent issue store renders the grey line, never "0 open" as clean', () => {
  delete process.env.CW_ISSUES; // the fixture root has no monitor/issues.json
  const s = gather({ root: fixtureRoot(), now: NOW });
  assert.equal(s.issues.state, 'absent');
  const md = renderMarkdown(s);
  assert.match(md, /## Issues/);
  assert.match(md, /no issue store \(tracker not yet initialised — explicit uncertainty\)/);
  assert.doesNotMatch(md, /Open \*\*0\*\*/);
  const html = renderHtml(s);
  assert.match(html, /no issue store/);
  assert.doesNotMatch(html, /Open <b>0<\/b>/);
});

