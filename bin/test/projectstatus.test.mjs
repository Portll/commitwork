// A paused area's rollup carries stateAtWrite:'fresh' forever — it was fresh when it was written,
// and nothing re-evaluates a baked value. Measured 2026-08-26: clientA rendered
// "1 repo(s) · 5h ago · fresh" while declared out of every sweep and publishing 1 of its 34 repos.
// The unit test for the `paused` freshness state passed the whole time; this consumer never called
// it. That is the shape of the defect, not the fix: a mechanism nothing on the page asks for.
function pausedRoot() {
  const root = fixtureRoot();
  writeFileSync(join(root, 'monitor/private/projects.json'), JSON.stringify({
    reportsRoot: 'reports',
    areas: [
      { slug: 'alpha', label: 'Alpha', out: 'alpha-out',
        paused: { since: '2026-08-26', reason: 'measured 10h+ run' } },
      { slug: 'ghost', label: 'Ghost', out: 'ghost' },
    ],
  }));
  return root;
}

test('a paused area reads PAUSED, not the fresh its own rollup baked in', () => {
  const before = gather({ root: fixtureRoot(), now: NOW }).fleet.find((a) => a.slug === 'alpha');
  assert.equal(before.freshness, 'fresh', 'the fixture must really claim fresh, or this proves nothing');

  const s = gather({ root: pausedRoot(), now: NOW });
  const alpha = s.fleet.find((a) => a.slug === 'alpha');
  assert.equal(alpha.freshness, 'paused');
  assert.deepEqual(alpha.paused, { since: '2026-08-26', reason: 'measured 10h+ run' });
  assert.match(renderMarkdown(s), /Alpha \|.*\| paused \|/, 'the rendered page is what a reader sees');
});

test('pausing does not blank the area — its findings still stand and are still shown', () => {
  const s = gather({ root: pausedRoot(), now: NOW });
  const alpha = s.fleet.find((a) => a.slug === 'alpha');
  assert.equal(alpha.scanned, true, 'a paused area with a rollup is scanned-but-not-current, not unscanned');
  assert.deepEqual(alpha.open, { crit: 1, high: 2, med: 3, low: 4 });
  assert.match(renderMarkdown(s), /crit 1 · high 2 · med 3 · low 4/);
});

test('an unpaused area is untouched by the mechanism — both directions', () => {
  const s = gather({ root: pausedRoot(), now: NOW });
  assert.equal(s.fleet.find((a) => a.slug === 'ghost').paused, undefined,
    'an unscanned area carries no paused key at all');
  const plain = gather({ root: fixtureRoot(), now: NOW }).fleet.find((a) => a.slug === 'alpha');
  assert.equal(plain.paused, null, 'a scanned, unpaused area says null — declared, not absent');
});
