#!/usr/bin/env node
// commitwork — docs-doctor: explicit uncertainty, applied to the documentation itself.
//
// Classifies every tracked markdown doc and exits nonzero when the doc set lies:
//   green   — durable doc with a fresh `verified-against:` stamp
//   orange  — needs updating: stale stamp, SUPERSEDED banner outside evaluations/archive/,
//             missing from the README doc index, or an index link to a missing or untracked file
//   grey    — unknown: durable doc with no stamp at all (never counts as green)
//   living  — a register whose CONTENT is current state (decisions, backlogs), marked
//             `<!-- living-doc -->` in its head: never archived, exempt from stamp freshness
//             (its normal condition is "recently edited"), but it must be listed in the README
//             index and stays off the reserved root — a register nobody can find is not living.
//             A doc that does not ship (an untracked sidecar register under evaluations/, or a
//             file .gitattributes marks export-ignore) is the exception: the index ships and
//             the doc does not, so listing it would publish a dead link
//   generated / archived / cycle — informational classes, never gated on freshness
//
// Stamp convention (first 10 lines of a durable doc):
//   <!-- verified-against: 2026-07-29 0a1b2c3 -->
// The date is when a human (or session) last checked the doc against HEAD; the sha is optional.
//
// Only a doc's HEAD is load-bearing: reads cap at 2KB, and a per-file (mtime, size) cache skips
// unchanged files. The cache stores parsed FACTS only — judgments are recomputed each run, so a
// cache hit never changes the output. CW_DOCS_CACHE overrides the path, CW_DOCS_CACHE=0 disables.
//
// Usage: node bin/docs-doctor.mjs [--json] [--root <dir>]
// Env:   CW_DOCS_MAX_AGE_DAYS (default 30), CW_NOW (ISO override for deterministic runs)
// Exit:  0 all green · 1 any orange · 2 grey only

