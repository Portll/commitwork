const SKIP_DIRS = new Set(['node_modules', '.git', 'reports', 'reference', 'tmp', '.npm-cache', '.claude',
  // test fixtures are inputs to tests, never documentation — an .md fixture stamp-gated here
  // would need a fake freshness stamp to pass, which is worse than not gating it
  'fixtures']);
// docsite content is PRODUCT content, not documentation: its own gates are
// bin/test/docsite-manifest.test.mjs (identity/pairing) and bin/docsite-build.mjs --check (drift),
// so stamp-governing it here would put one tree under the wrong tier. PATH-scoped, not name-scoped
// — 'content' in SKIP_DIRS would skip every dir of that name anywhere in the repo. docsite/editor
// is deliberately NOT skipped: any .md that appears there is documentation.
const SKIP_PATHS = new Set(['docsite/content', 'docsite/pages', 'docsite/imported',
  // the private records dir (a link into the sidecar): its .md files are operational records and
  // private draft documents, not this repository's documentation
  'monitor/private',
  // prompts/ are LLM tool INPUTS, read by the tools that send them, the same class as fixtures.
  'prompts',
  // Draft issue and pull-request texts addressed to joern's maintainers: outbound correspondence
  // for another project, not documentation of this one.
  'joernwork/upstream-drafts']);
// LICENSING.md joins these 2026-08-22. Root is reserved so docs cannot accumulate there, but a
// licence statement has no module to live in and belongs where a reader looks for it — the same
// argument that puts README here. LICENSE itself is never scanned (not .md).
// fact: BACKLOG-commitwork.md and PROJECTSTATUS.md left root 2026-09-30 for the sidecar; they are operational records
const ROOT_ALLOWED = new Set(['README.md', 'CLAUDE.md', 'LICENSING.md']);
const STAMP_RE = /<!--\s*verified-against:\s*(\d{4}-\d{2}-\d{2})(?:\s+([0-9a-f]{7,40}))?\s*-->/;
// A banner that supersedes part of a doc (a correction at its foot) leaves the rest current, so
// the doc is not a closed cycle and does not belong in the archive.
const SUPERSEDED_RE = /\*\*SUPERSEDED(?!\s+IN\s+PART)/i;
const GENERATED_RE = /generated by/i;
// A living doc DECLARES itself — path/filename classification would make the tier ambient.
const LIVING_RE = /<!--\s*living-doc\s*-->/;

// A cycle artifact is identified by a date's PRESENCE in its filename, not its position. Anchored
// on a `-`/`_` boundary so a version-like `v2026-07-30` reads but digits inside a word cannot.
const DATE_IN_NAME_RE = /(?:^|[-_])(\d{4}-\d{2}-\d{2})(?=[-_.]|$)/;

// Digit-shaped is not REAL: 2026-13-45 satisfies the regex but names no day. Round-trip through
// Date in UTC so timezone cannot shift the verdict.
export function realDate(s) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(s);
  if (!m) return false;
  const [y, mo, d] = [+m[1], +m[2], +m[3]];
  const dt = new Date(Date.UTC(y, mo - 1, d));
  return dt.getUTCFullYear() === y && dt.getUTCMonth() === mo - 1 && dt.getUTCDate() === d;
}

// The KINDS that are cycle artifacts: prefix (what it IS) plus date (which cycle) both required,
// because cycle status suppresses all three durable checks and a date alone would make the root
// allowlist opt-out-able by filename.
const CYCLE_KINDS = /^(REMEDIATION|SCANNER-BACKLOG)-/;

// True for a ROOT-level dated cycle artifact. Root-only: in a module a dated filename is durable.
// The "one open cycle at root" cap is not enforced here — it needs a human's closed/open judgment.
export function datedCycleDoc(rel) {
  if (rel.includes('/')) return false;
  if (!CYCLE_KINDS.test(rel)) return false;
  const m = DATE_IN_NAME_RE.exec(rel.replace(/\.md$/, ''));
  return !!m && realDate(m[1]);
}

export function repoRoot() {
  return resolve(dirname(fileURLToPath(import.meta.url)), '..');
}

// `rel` is POSIX-separated, ALWAYS, and normalised HERE rather than at each use.
//
// `relative()` is `path.win32.relative` on Windows, so this pushed `sitemap\README.md`. Everything
// downstream then compared that against two things that always use forward slashes — the
// `git ls-files` tracked set, and `rel.includes('/')` as the test for "is this doc at the root".
// Both answered wrongly for EVERY module doc on Windows: each one was reported as living at the
// root ("root is reserved for README/BACKLOG/PROJECTSTATUS/CLAUDE") *and* as untracked ("this doc
// does not exist for anyone but its author") while sitting in git the whole time.
//
// The partial fix was already here — the SKIP_PATHS lookup on the line below normalised, and
// nothing else did — which is the signature of somebody hitting one symptom and patching it where
// it hurt rather than where it came from. Same defect and same shape as bin/lib/tracked-imports.mjs
// building candidates with `path.join`: a doc gate that flags every document is a doc gate nobody
// can read, which is the same as not having one.
const toPosix = (p) => String(p).split('\\').join('/');

function walk(dir, root, out) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) {
      if (!SKIP_DIRS.has(name) && !SKIP_PATHS.has(toPosix(relative(root, p)))) walk(p, root, out);
    } else if (name.endsWith('.md')) {
      out.push({ rel: toPosix(relative(root, p)), mtimeMs: st.mtimeMs, size: st.size });
    }
  }
  return out;
}

// Only a doc's head is load-bearing, so read at most HEAD_BYTES.
const HEAD_BYTES = 2048;
function head(root, rel) {
  const fd = openSync(join(root, rel), 'r');
  try {
    const buf = Buffer.alloc(HEAD_BYTES);
    const n = readSync(fd, buf, 0, HEAD_BYTES, 0);
    return buf.toString('utf8', 0, n).split('\n').slice(0, 10).join('\n');
  } finally {
    closeSync(fd);
  }
}

// Facts a doc's head yields (cacheable per mtime/size), separated from the judgments about them
// (recomputed every run).
function parseFacts(first) {
  const m = first.match(STAMP_RE);
  return {
    title: (first.match(/^#\s+(.+)$/m) || [])[1] || null,
    generated: GENERATED_RE.test(first),
    superseded: SUPERSEDED_RE.test(first),
    living: LIVING_RE.test(first),
    stamp: m ? { date: m[1], sha: m[2] || null } : null,
  };
}

// 2 gained `living`; 3 stopped reading a SUPERSEDED IN PART banner as superseded.
const CACHE_VERSION = 3;
function loadCache(cachePath) {
  if (!cachePath) return null;
  try {
    const c = JSON.parse(readFileSync(cachePath, 'utf8'));
    // A cache from another version holds facts parsed by other rules: invalidate, never coexist.
    return c && c.version === CACHE_VERSION && c.files ? c : { version: CACHE_VERSION, files: {} };
  } catch {
    return { version: CACHE_VERSION, files: {} }; // cache is a perf layer — unreadable means cold, never fatal
  }
}

function saveCache(cachePath, cache) {
  try {
    mkdirSync(dirname(cachePath), { recursive: true });
    writeAtomic(cachePath, JSON.stringify(cache));
  } catch { /* read-only FS must not break the doctor */ }
}

// The doc index is the `## Documentation` section of README.md; a durable doc is "listed"
// when its repo-relative path appears as a markdown link target there.
function indexTargets(root) {
  const readme = join(root, 'README.md');
  if (!existsSync(readme)) return { targets: null, reason: 'README.md missing' };
  const text = readFileSync(readme, 'utf8');
  const start = text.indexOf('\n## Documentation\n');
  if (start < 0) return { targets: null, reason: 'README.md has no "## Documentation" index section' };
  const rest = text.slice(start + 1);
  const end = rest.indexOf('\n## ');
  const section = end < 0 ? rest : rest.slice(0, end);
  const targets = new Set();
  // An index entry's description may link out (`[joernio/joern](https://…)`); a URL is not a doc
  // path, and checking it on disk reported the index as linking to a missing file.
  for (const link of section.matchAll(/\]\(([^)#]+)\)/g)) {
    if (/^[a-z][a-z0-9+.-]*:/i.test(link[1])) continue;
    targets.add(link[1].replace(/^\.\//, ''));
  }
  return { targets };
}

// ── TRACKED-NESS ────────────────────────────────────────────────────────────────────────────────
// A doc that is not in the repository does not exist for anybody but its author, however fresh its
// stamp is. Until 2026-08-30 this gate never asked: an untracked, stamped, README-listed doc scored
// GREEN and the run exited 0, proved by fixture probe.
//
// A POSITIVE SET, deliberately — `git ls-files`, never `git ls-files --others --exclude-standard`.
// The negative form EXCLUDES IGNORED PATHS, so a doc hidden under an ignore rule is invisible to the
// very check whose job is finding hidden docs; that blind spot and the thing it hid were one
// mechanism, and it is recorded in CLAUDE.md because it cost months. Asking "is it in the tracked
// set" cannot have that hole: an ignored file is simply not in the set.
//
// Three-state, because absent evidence is not evidence of absence:
//   Set  = the tracked paths        · null = NOT A REPO (inapplicable, the one silent skip, as
//   gitStaleness does)              · undefined = git present but UNREADABLE ⇒ UNKNOWN, never green.
function trackedSet(root, { enabled = process.env.CW_DOCS_GIT !== '0' } = {}) {
  if (!enabled) return null;
  const git = (args) => {
    const r = spawnSync('git', ['-C', root, ...args], { encoding: 'utf8' });
    if (r.error || r.status !== 0) return null;
    return r.stdout;
  };
  if (git(['rev-parse', '--is-inside-work-tree']) === null) return null;   // not a repo
  const out = git(['ls-files', '-z']);
  if (out === null) return undefined;                                      // repo, but unreadable
  return new Set(out.split('\0').filter(Boolean));
}

// Tracked files .gitattributes keeps out of `git archive`, which is how the published snapshot is
// built. An unreadable answer is an empty set: the index rules then fall back to requiring the doc.
function exportIgnoredSet(root, tracked) {
  if (!(tracked instanceof Set) || !tracked.size) return new Set();
  const r = spawnSync('git', ['-C', root, 'check-attr', '-z', '--stdin', 'export-ignore'], { input: [...tracked].join('\0'), encoding: 'utf8', maxBuffer: 1 << 26 });
  if (r.error || r.status !== 0) return new Set();
  const out = new Set();
  const f = r.stdout.split('\0');
  for (let i = 0; i + 2 < f.length; i += 3) if (f[i + 2] === 'set') out.add(f[i]);
  return out;
}

// ── THE SHA HALF OF THE STAMP ───────────────────────────────────────────────────────────────────
// Enforces the sha, not just the date: if the doc changed since its stamp was written, it is stale.
// Exact, not heuristic — editing a doc without re-stamping is precisely the violation.
function gitStaleness(root, docs, { enabled = process.env.CW_DOCS_GIT !== '0' } = {}) {
  const out = new Map();
  if (!enabled) return out;
  const git = (args) => {
    const r = spawnSync('git', ['-C', root, ...args], { encoding: 'utf8' });
    if (r.error || r.status !== 0) return null;
    return r.stdout;
  };
  // No repo (a fixture dir) makes the check inapplicable, not failed — the one silent skip.
  if (git(['rev-parse', '--is-inside-work-tree']) === null) return out;

  const flag = (p, v) => out.set(p, [...(out.get(p) || []), v]);
  for (const d of docs) {
    if (!d.stamp || !d.stamp.sha) continue;

    // A sha this repo does not contain is no evidence — most likely it names the repo the doc is ABOUT.
    if (git(['cat-file', '-e', `${d.stamp.sha}^{commit}`]) === null) {
      flag(d.path, { kind: 'unknown-sha', detail: `stamp names commit ${d.stamp.sha}, which this repository does not contain` });
      continue;
    }
    // Existence is not membership: a rewritten or abandoned commit stays in the object store until gc,
    // so it resolves here and in no clone. Exit 1 is "not an ancestor"; anything else is a failed check.
    const anc = spawnSync('git', ['-C', root, 'merge-base', '--is-ancestor', `${d.stamp.sha}^{commit}`, 'HEAD'], { encoding: 'utf8' });
    if (anc.error || (anc.status !== 0 && anc.status !== 1)) {
      flag(d.path, { kind: 'check-failed', detail: `could not test whether ${d.stamp.sha} is in HEAD's history; refusing to report the doc as verified` });
      continue;
    }
    if (anc.status === 1) {
      flag(d.path, { kind: 'not-in-history', detail: `stamp names commit ${d.stamp.sha}, which exists here but is not in HEAD's history — no clone of this branch can resolve it` });
    }

    // The anchor is the commit that WROTE the stamp, not the one the stamp names: verifying a doc
    // usually corrects it, so fix and stamp land together and <stamped-sha>..HEAD false-flags.
    const stampLine = `verified-against: ${d.stamp.date} ${d.stamp.sha}`;
    const introduced = git(['log', '-1', '--format=%H', '-S', stampLine, '--', d.path]);
    if (introduced === null) {
      flag(d.path, { kind: 'check-failed', detail: `could not locate the commit that wrote this stamp; refusing to report the doc as verified` });
      continue;
    }
    const anchor = introduced.trim();
    // No committed stamp yet (working-tree only): HEAD makes no claim, nothing to check.
    if (!anchor) continue;

    const since = git(['rev-list', '--count', `${anchor}..HEAD`, '--', d.path]);
    if (since === null) {
      flag(d.path, { kind: 'check-failed', detail: `could not count commits since ${anchor.slice(0, 7)}; refusing to report this as verified` });
      continue;
    }
    const n = Number(since.trim());
    if (n > 0) {
      flag(d.path, { kind: 'edited-since', detail: `changed in ${n} commit(s) since the stamp was written (stamp names ${d.stamp.sha}) — re-verify and refresh it` });
    }
  }
  return out;
}

export function collectDocs({
  root = repoRoot(),
  now = process.env.CW_NOW ? new Date(process.env.CW_NOW) : new Date(),
  maxAgeDays = Number(process.env.CW_DOCS_MAX_AGE_DAYS || 30),
  git = process.env.CW_DOCS_GIT !== '0',
  cachePath = process.env.CW_DOCS_CACHE === '0' ? null
    : (process.env.CW_DOCS_CACHE || join(root, 'reports', '.docs-doctor-cache.json')),
} = {}) {
  const docs = [];
  const { targets, reason: indexReason } = indexTargets(root);
  const tracked = trackedSet(root, { enabled: git });
  const exportIgnored = exportIgnoredSet(root, tracked);
  const unshipped = (rel) => exportIgnored.has(rel) || (rel.startsWith('evaluations/') && tracked instanceof Set && !tracked.has(rel));
  const cache = loadCache(cachePath);
  const nextFiles = {};
  let readCount = 0;
  for (const { rel, mtimeMs, size } of walk(root, root, [])) {
    const hit = cache?.files[rel];
    let facts;
    if (hit && hit.mtimeMs === mtimeMs && hit.size === size) {
      facts = hit.facts; // unchanged since last run — not reopened
    } else {
      facts = parseFacts(head(root, rel));
      readCount++;
    }
    nextFiles[rel] = { mtimeMs, size, facts };
    const doc = { path: rel, title: facts.title || rel, status: null, reasons: [], stamp: null };

    if (facts.generated) {
      doc.status = 'generated';
    } else if (rel.startsWith('evaluations/archive/')) {
      doc.status = 'archived';
      if (!facts.superseded) { doc.status = 'orange'; doc.reasons.push('archived doc without a SUPERSEDED banner'); }
    } else if (facts.superseded) {
      doc.status = 'orange';
      doc.reasons.push('carries a SUPERSEDED banner but lives outside evaluations/archive/');
    } else if (facts.living) {
      // Living (before the evaluations/ path rule): content IS current state, so stamp freshness
      // never gates; a stamp, if present, is informational provenance.
      doc.status = 'living';
      if (facts.stamp) doc.stamp = facts.stamp;
      if (targets && !targets.has(rel) && !unshipped(rel)) { doc.status = 'orange'; doc.reasons.push('living register not listed in the README "## Documentation" index — a register nobody can find is not living'); }
      if (!rel.includes('/') && !ROOT_ALLOWED.has(rel)) { doc.status = 'orange'; doc.reasons.push('root is reserved for README/BACKLOG/PROJECTSTATUS/CLAUDE — move to its module or evaluations/'); }
    } else if (rel.startsWith('evaluations/') || datedCycleDoc(rel)) {
      doc.status = 'cycle';
      if (!rel.startsWith('evaluations/')) doc.reasons.push('cycle doc at repo root — move under evaluations/<cycle>/ when the cycle closes');
    } else {
      // durable doc: stamp decides green/orange/grey; the index decides listed-ness
      if (!facts.stamp) {
        doc.status = 'grey';
        doc.reasons.push('no verified-against stamp — freshness unknown');
      } else {
        doc.stamp = facts.stamp;
        const ageDays = (now - new Date(facts.stamp.date + 'T00:00:00Z')) / 86400000;
        if (ageDays > maxAgeDays) { doc.status = 'orange'; doc.reasons.push(`verified-against ${facts.stamp.date} is older than ${maxAgeDays} days`); }
        else doc.status = 'green';
      }
      // README.md IS the index; it does not have to list itself
      if (targets && rel !== 'README.md' && !targets.has(rel) && !unshipped(rel)) { doc.status = 'orange'; doc.reasons.push('not listed in the README "## Documentation" index'); }
      const parts = rel.split('/');
      if (parts.length === 1 && !ROOT_ALLOWED.has(rel)) { doc.status = 'orange'; doc.reasons.push('root is reserved for README/BACKLOG/PROJECTSTATUS/CLAUDE — move to its module or evaluations/'); }
    }
    docs.push(doc);
  }
  if (cachePath) saveCache(cachePath, { version: CACHE_VERSION, files: nextFiles });
  // Recomputed every run, outside the cache — see gitStaleness().
  const stale = gitStaleness(root, docs, { enabled: git });
  for (const d of docs) {
    const vs = stale.get(d.path);
    // Only durable docs answer to the stamp; generated/archived/cycle make no claim about the tree.
    if (!vs || (d.status !== 'green' && d.status !== 'orange' && d.status !== 'grey')) continue;
    d.status = 'orange';
    for (const v of vs) d.reasons.push(v.detail);
  }
  // TRACKED-NESS, applied only to docs that make a claim about this tree. A generated or archived
  // doc is not asserting anything a clone must be able to read.
  if (tracked !== null) {
    for (const d of docs) {
      if (d.status !== 'green' && d.status !== 'orange' && d.status !== 'grey') continue;
      if (tracked === undefined) {
        // git answered nothing. That is "we could not tell", which is NOT "it is fine" — a green
        // here would be the gate certifying a fact it never established.
        if (d.status === 'green') { d.status = 'grey'; d.reasons.push('tracked-ness UNKNOWN — git could not be read'); }
        continue;
      }
      // evaluations/ IS UNTRACKED ON PURPOSE — operator instruction 2026-08-26, and since
      // 2026-08-27 the path is a symlink to the private sidecar repo, where these records DO have
      // version history. Flagging them would be the gate reporting policy as a defect, and a gate
      // that cries wolf about the intended state teaches its reader to ignore the real case.
      // Narrow and named rather than a general "skip anything untracked", which would restore the
      // hole this check exists to close.
      if (d.path.startsWith('evaluations/')) continue;
      if (!tracked.has(d.path)) {
        d.status = 'untracked';
        d.reasons.push('not tracked in git — this doc does not exist for anyone but its author');
      }
    }
  }
  const findings = [];
  if (indexReason) findings.push({ path: 'README.md', reason: indexReason });
  if (targets) {
    for (const t of targets) {
      if (!existsSync(join(root, t))) findings.push({ path: 'README.md', reason: `doc index links to missing file: ${t}` });
      // Resolving on disk alone made a sidecar link look present to its author and dangle in every
      // clone, so the gate saw it only on a snapshot.
      else if (tracked instanceof Set && !tracked.has(t) && ![...tracked].some((p) => p.startsWith(`${t.replace(/\/$/, '')}/`))) {
        findings.push({ path: 'README.md', reason: `doc index links to an untracked file a clone will not have: ${t}` });
      } else if (exportIgnored.has(t)) {
        findings.push({ path: 'README.md', reason: `doc index links to an export-ignored file the published snapshot will not have: ${t}` });
      }
    }
  }
  return { generatedAt: now.toISOString(), root, maxAgeDays, docs, indexFindings: findings, readCount };
}

export function verdict(result) {
  // `untracked` is its own state and its own reason, never folded into orange: orange means "this
  // doc needs updating", untracked means "this doc is not in the repository at all". Conflating them
  // would report a missing document as a stale one. It ranks with orange for EXIT purposes because
  // both are failures a human must act on, and the exit contract (1 = act, 2 = unknown) is depended
  // on by callers.
  const untracked = result.docs.filter((d) => d.status === 'untracked').length;
  const orange = result.docs.filter((d) => d.status === 'orange').length + result.indexFindings.length;
  const grey = result.docs.filter((d) => d.status === 'grey').length;
  return (orange || untracked) ? 1 : grey ? 2 : 0;
}

/** The STABLE raw form of a scan result, for `measured.digest`. Strips `generatedAt` and
 *  `readCount` — properties of the RUN, not the doc set — so the digest can say "stuck". */
export function measurementRaw(result) {
  const { generatedAt, readCount, ...stable } = result;
  return JSON.stringify(stable);
}

