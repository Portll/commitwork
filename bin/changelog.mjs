#!/usr/bin/env node
// usage: changelog.mjs [--from <tag|sha>] [--to <ref>] [--stdout]
// exit: 0 section written or printed · 20 no release tag precedes --to and no --from was given · 21 git failed, a ref did not resolve, or the changelog could not be read or is not generated · 22 usage
// env, read at call time: CW_REPO_ROOT (the repository read), CW_CHANGELOG_OUT (the file written, default docs/CHANGELOG.md), CW_NOW (the section date), CW_RELEASE_TAG_PREFIX (the release tag prefix, default v)
// output: one section per range in docs/CHANGELOG.md, newest first, written tmp+rename; --stdout prints the section and writes nothing
//
// pins: the default range is the nearest release tag before --to, up to --to (default HEAD)
// pins: a section's identity is its heading label; regenerating a range replaces it in place
// pins: the date is CW_NOW when set, else the --to commit's committer date, so a re-run is byte-identical
// guard: a subject that is not conventional is listed under its own heading, never dropped
// pins: it describes only the repository it runs in; bin/test/changelog.test.mjs fails a tracked section citing a commit this repository lacks

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMainModule } from '../lib/is-main.mjs';
import { nowISO } from '../lib/clock.mjs';
import { writeAtomic } from '../monitor/lockfile.mjs';
import { scannedGit } from './lib/git-env.mjs';
import { validateConventional } from './lib/conventional-commit.mjs';
import { tagPrefix } from './release-tag.mjs';

export const EXIT = { OK: 0, NO_START: 20, UNREADABLE: 21, USAGE: 22 };

const REPO = () => process.env.CW_REPO_ROOT || dirname(dirname(fileURLToPath(import.meta.url)));
export const outPath = (repo = REPO()) => process.env.CW_CHANGELOG_OUT || join(repo, 'docs', 'CHANGELOG.md');
export const releaseMatch = () => `${tagPrefix()}[0-9]*`;

export const UNRELEASED = 'Unreleased';
export const GENERATED_MARK = 'Generated by bin/changelog.mjs';

export const PREAMBLE = [
  `<!-- ${GENERATED_MARK} -- do not hand-edit; regenerate the section instead. -->`,
  '# Changelog',
  '',
  'Each section below is generated from one release\'s commit range by `node bin/changelog.mjs`.',
  'A release is a tag naming the version `package.json` carries at that commit',
  '([docs/RELEASING.md](RELEASING.md)); the default range runs from the nearest earlier release tag to',
  'the commit being released. Commits are grouped by their conventional-commit type, breaking changes',
  'first, one line each with the short commit id. A subject that does not parse as a conventional',
  'commit is listed under "Not conventional" rather than left out.',
  '',
  'Sections describe the history of the repository this file is in, and only that history. A file',
  'with no sections below has no release cut from this history yet. Withdrawing or rolling back a',
  'release is in [docs/RELEASE-RUNBOOK.md](RELEASE-RUNBOOK.md).',
  '',
].join('\n');

const TYPE_HEADINGS = [
  ['feat', 'Features'], ['fix', 'Fixes'], ['perf', 'Performance'], ['refactor', 'Refactoring'],
  ['revert', 'Reverts'], ['docs', 'Documentation'], ['test', 'Tests'], ['build', 'Build'],
  ['ci', 'CI'], ['style', 'Style'], ['chore', 'Chores'],
];
const KNOWN = new Map(TYPE_HEADINGS);

export class ChangelogError extends Error {}

function git(args, cwd) {
  const r = scannedGit(cwd, args, { timeout: 60_000, maxBuffer: 1 << 26 });
  if (r.error) throw new ChangelogError(`git could not be run: ${r.error.message}`);
  return { status: r.status, stdout: String(r.stdout || ''), stderr: String(r.stderr || '').trim() };
}
function gitOut(args, cwd) {
  const r = git(args, cwd);
  if (r.status !== 0) throw new ChangelogError(`git ${args[0]} exited ${r.status}: ${r.stderr.split('\n')[0].slice(0, 160)}`);
  return r.stdout;
}

/** @returns {string} the full commit id `ref` names / throws ChangelogError when it names none */
export function resolveCommit(ref, cwd = REPO()) {
  const r = git(['rev-parse', '--verify', '-q', `${ref}^{commit}`], cwd);
  if (r.status !== 0) throw new ChangelogError(`${JSON.stringify(ref)} does not name a commit in ${cwd}`);
  return r.stdout.trim();
}

/** @returns {string|null} the nearest release tag strictly before `to`, null when there is none */
export function previousTag(to, cwd = REPO()) {
  const sha = resolveCommit(to, cwd);
  const parents = gitOut(['rev-list', '--parents', '-n', '1', sha], cwd).trim().split(/\s+/).slice(1);
  if (!parents.length) return null;
  const r = git(['describe', '--tags', '--abbrev=0', '--match', releaseMatch(), parents[0]], cwd);
  if (r.status === 0) return r.stdout.trim();
  // fact: describe exits 128 for "no tag" and for a broken repository alike / only its message tells them apart (expiry: if git changes the wording, prev: missing)
  if (/no names found|no tags can describe|cannot describe/i.test(r.stderr)) return null;
  throw new ChangelogError(`git describe exited ${r.status}: ${r.stderr.split('\n')[0].slice(0, 160)}`);
}

/** @returns {string|null} the release tag on `to`: `to` itself when it is one, else the first pointing at its commit */
export function tagAt(to, cwd = REPO()) {
  const sha = resolveCommit(to, cwd);
  const names = gitOut(['tag', '--list', releaseMatch(), '--points-at', sha], cwd).split('\n').filter(Boolean).sort();
  return names.includes(to) ? to : names[0] || null;
}

/** @returns {{sha:string, message:string}[]} the non-merge commits in from..to, plus the merge count */
export function readRange(from, to, cwd = REPO()) {
  const a = resolveCommit(from, cwd);
  const b = resolveCommit(to, cwd);
  const raw = gitOut(['log', '-z', '--no-merges', '--format=%H%n%B', `${a}..${b}`], cwd);
  const commits = raw.split('\0').filter((r) => r.trim()).map((r) => {
    const nl = r.indexOf('\n');
    return { sha: (nl < 0 ? r : r.slice(0, nl)).trim(), message: nl < 0 ? '' : r.slice(nl + 1) };
  });
  const merges = Number(gitOut(['rev-list', '--count', '--merges', `${a}..${b}`], cwd).trim());
  return { commits, merges: Number.isFinite(merges) ? merges : 0 };
}

/** @returns {{type:string|null, scope:string|null, breaking:boolean, description:string, note:string|null}} */
export function classify(message) {
  const v = validateConventional(message, {
    allowedTypes: null, allowedScopes: null, subjectMax: 0, checkTells: false, checkMood: false,
  });
  const subject = String(message).replace(/\r\n?/g, '\n').split('\n')[0].trim();
  const p = v.parsed;
  if (!p) return { type: null, scope: null, breaking: false, description: subject, note: null };
  if (p.exempt === 'revert') return { type: 'revert', scope: null, breaking: false, description: subject, note: null };
  if (p.exempt) return { type: null, scope: null, breaking: false, description: subject, note: null };
  const footer = p.footers.find((f) => f.token === 'BREAKING CHANGE' || f.token === 'BREAKING-CHANGE');
  return {
    type: p.type.toLowerCase(), scope: p.scope, breaking: p.breaking, description: p.description.trim(),
    note: footer ? footer.value.split('\n')[0].trim() || null : null,
  };
}

// guard: commit text is untrusted input; markdown would render a raw `<` as HTML
const clean = (s) => String(s).replace(/[\u0000-\u001F\u007F]/g, ' ').replace(/</g, '&lt;').trim();

const short = (sha) => sha.slice(0, 8);

function entryLine(c, { withType }) {
  const label = withType ? `${c.type}${c.scope ? `(${c.scope})` : ''}` : c.scope;
  const head = label ? `**${clean(label)}:** ` : '';
  const note = c.note ? ` BREAKING CHANGE: ${clean(c.note)}` : '';
  return `- ${head}${clean(c.description)}${note} (\`${short(c.sha)}\`)`;
}

const byOrder = (a, b) => (a.scope || '').localeCompare(b.scope || '', 'en')
  || a.description.localeCompare(b.description, 'en') || a.sha.localeCompare(b.sha);

/** @returns {{heading:string, entries:object[]}[]} groups in output order, empty ones omitted */
export function group(commits) {
  const rows = commits.map((c) => ({ ...classify(c.message), sha: c.sha }));
  const out = [];
  const push = (heading, entries, withType) => {
    if (entries.length) out.push({ heading, lines: entries.sort(byOrder).map((e) => entryLine(e, { withType })) });
  };
  push('Breaking changes', rows.filter((r) => r.breaking), true);
  const rest = rows.filter((r) => !r.breaking);
  for (const [type, heading] of TYPE_HEADINGS) push(heading, rest.filter((r) => r.type === type), false);
  const other = [...new Set(rest.filter((r) => r.type && !KNOWN.has(r.type)).map((r) => r.type))].sort();
  for (const type of other) push(`Other: ${type}`, rest.filter((r) => r.type === type), false);
  push('Not conventional', rest.filter((r) => !r.type), false);
  return out;
}

/** The markdown section for one range. Pure. */
export function renderSection({ label, date, fromLabel, toLabel, commits, merges = 0 }) {
  const count = `${commits.length} commit${commits.length === 1 ? '' : 's'}`;
  const mergeNote = merges ? ` · ${merges} merge commit${merges === 1 ? '' : 's'} not listed` : '';
  const lines = [`## ${label} — ${date}`, '', `\`${fromLabel}..${toLabel}\` · ${count}${mergeNote}`, ''];
  const groups = group(commits);
  if (!groups.length) lines.push('No commits in this range.', '');
  for (const g of groups) lines.push(`### ${g.heading}`, '', ...g.lines, '');
  return `${lines.join('\n').trimEnd()}\n`;
}

const sectionKey = (section) => section.split('\n')[0].replace(/^## /, '').split(' — ')[0].trim();

/** Insert `section` into an existing changelog: same label replaces in place, a new label goes first. */
export function upsert(existing, section) {
  const text = existing == null ? '' : String(existing).replace(/\r\n?/g, '\n');
  const at = text.search(/^## /m);
  const body = at < 0 ? '' : text.slice(at);
  let sections = body ? body.split(/\n(?=## )/).map((s) => `${s.trimEnd()}\n`) : [];
  const key = sectionKey(section);
  // a release absorbs the commits an Unreleased section listed, so the old one is stale
  if (key !== UNRELEASED) sections = sections.filter((s) => sectionKey(s) !== UNRELEASED);
  const i = sections.findIndex((s) => sectionKey(s) === key);
  if (i >= 0) sections[i] = section;
  else sections.unshift(section);
  sections.sort((a, b) => (sectionKey(b) === UNRELEASED) - (sectionKey(a) === UNRELEASED));
  return `${PREAMBLE}\n${sections.join('\n')}`.replace(/\n+$/, '\n');
}

/** @returns {string|null} the changelog's text, null when absent / throws on anything but ENOENT, or a file this tool did not write */
export function readChangelog(path) {
  let text;
  try { text = readFileSync(path, 'utf8'); } catch (e) {
    if (e.code === 'ENOENT') return null;
    throw new ChangelogError(`${path} could not be read (${e.code || e.message})`);
  }
  if (!text.split('\n').slice(0, 10).join('\n').includes(GENERATED_MARK)) {
    throw new ChangelogError(`${path} does not carry "${GENERATED_MARK}" in its head -- refusing to overwrite a file this tool did not write`);
  }
  return text;
}

/** Plan one section. @returns {{section:string, from:string, to:string, label:string}} / null `from` means no start */
export function build({ from = null, to = 'HEAD', cwd = REPO() } = {}) {
  const start = from || previousTag(to, cwd);
  if (!start) return { from: null, to };
  const { commits, merges } = readRange(start, to, cwd);
  const label = tagAt(to, cwd) || UNRELEASED;
  const date = (process.env.CW_NOW ? nowISO() : new Date(gitOut(['show', '-s', '--format=%cI', resolveCommit(to, cwd)], cwd).trim()).toISOString()).slice(0, 10);
  const named = (ref) => (/^[0-9a-f]{7,64}$/i.test(ref) ? short(ref) : ref);
  const section = renderSection({ label, date, fromLabel: named(start), toLabel: named(to), commits, merges });
  return { section, from: start, to, label, commits: commits.length };
}

function main(argv) {
  const known = new Set(['--from', '--to', '--stdout']);
  const val = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : undefined; };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!known.has(a)) { console.error(`changelog: unknown argument ${JSON.stringify(a)}\nusage: changelog.mjs [--from <tag|sha>] [--to <ref>] [--stdout]`); return EXIT.USAGE; }
    if (a !== '--stdout') {
      if (!argv[i + 1] || argv[i + 1].startsWith('--')) { console.error(`changelog: ${a} needs a value`); return EXIT.USAGE; }
      i += 1;
    }
  }
  const to = val('--to') || 'HEAD';
  let plan;
  try { plan = build({ from: val('--from') || null, to }); } catch (e) {
    console.error(`changelog: ${e.message} -- the range is UNREAD, nothing written`);
    return EXIT.UNREADABLE;
  }
  if (!plan.from) {
    console.error(`changelog: no tag matching ${releaseMatch()} precedes ${to}, so the range has no start -- pass --from <tag|sha>; nothing written`);
    return EXIT.NO_START;
  }
  if (argv.includes('--stdout')) { process.stdout.write(plan.section); return EXIT.OK; }
  const out = outPath();
  let existing;
  try { existing = readChangelog(out); } catch (e) {
    console.error(`changelog: ${e.message}; nothing written`);
    return EXIT.UNREADABLE;
  }
  writeAtomic(out, upsert(existing, plan.section), { mkdir: true });
  console.log(`changelog: ${plan.label} (${plan.from}..${plan.to}, ${plan.commits} commit${plan.commits === 1 ? '' : 's'}) -> ${out}`);
  return EXIT.OK;
}

if (isMainModule(import.meta.url)) process.exitCode = main(process.argv.slice(2));
