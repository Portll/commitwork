#!/usr/bin/env node
// usage: panel-local-name.mjs [--write] [--check]
// exit: 0 written, or commitwork.local reaches the panel · 1 --check: it does not, with the step
//       that failed · 2 usage error or a write failed
// env, read at call time: CW_ADMIN_PORT, CW_ADMIN_LOCAL_PORT, CW_PANEL_LOCAL_DIR
// output: install.sh and uninstall.sh in reports/panel-local-name/, for the operator to read and run
//         with sudo; this tool never runs anything as root
//
// pins: http://commitwork.local opens the operator port, the panel's local listener
// fact: binding loopback :80 needs root on macOS / a pf rdr rule moves :80 to the operator port instead
// fact: the rule is a sub-anchor of the com.apple rdr-anchor in /etc/pf.conf / so pf.conf itself is never edited, and an OS update that rewrites it keeps the rule
// fact: ::1 is listed beside 127.0.0.1 / a .local name with no AAAA answer in /etc/hosts waits on an mDNS lookup first

import { lookup as dnsLookup } from 'node:dns/promises';
import { request } from 'node:http';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeAtomic } from '../monitor/lockfile.mjs';
import { isMainModule } from '../lib/is-main.mjs';
import { PANEL_LOCAL_NAME, PANEL_LOCAL_HTTP_PORT } from '../admin/local-access.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
export const outDir = () => process.env.CW_PANEL_LOCAL_DIR || join(REPO, 'reports', 'panel-local-name');
export const operatorPort = () => +(process.env.CW_ADMIN_LOCAL_PORT || (+(process.env.CW_ADMIN_PORT || 7878) + 1));

export const LABEL = 'net.portll.commitwork-local';
export const ANCHOR = `com.apple/250.${LABEL}`;
const ANCHOR_FILE = `/etc/pf.anchors/${LABEL}`;
const DAEMON = `/Library/LaunchDaemons/${LABEL}.plist`;
const BEGIN = `# >>> ${PANEL_LOCAL_NAME} (bin/panel-local-name.mjs)`;
const END = `# <<< ${PANEL_LOCAL_NAME}`;

const header = (what) => `#!/bin/sh
# Generated by bin/panel-local-name.mjs. ${what}
# Read it, then run it with sudo. Each step is idempotent.
set -eu
[ "$(id -u)" = 0 ] || { echo "run this with sudo" >&2; exit 1; }
`;
const dropHostsBlock = `sed -i '' '/^# >>> ${PANEL_LOCAL_NAME} /,/^# <<< ${PANEL_LOCAL_NAME}$/d' /etc/hosts`;
const flush = 'dscacheutil -flushcache\nkillall -HUP mDNSResponder';

export function renderInstall(port) {
  const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${LABEL}</string>
  <key>ProgramArguments</key>
  <array><string>/sbin/pfctl</string><string>-E</string><string>-a</string><string>${ANCHOR}</string><string>-f</string><string>${ANCHOR_FILE}</string></array>
  <key>RunAtLoad</key><true/>
</dict>
</plist>`;
  return `${header(`Makes http://${PANEL_LOCAL_NAME} open the panel's operator port, 127.0.0.1:${port}.`)}
# 1. The name, as a marked block in /etc/hosts that a re-run replaces.
${dropHostsBlock}
cat >> /etc/hosts <<'HOSTS'
${BEGIN}
127.0.0.1 ${PANEL_LOCAL_NAME}
::1 ${PANEL_LOCAL_NAME}
${END}
HOSTS

# 2. Loopback port ${PANEL_LOCAL_HTTP_PORT} to the operator port, in a sub-anchor /etc/pf.conf already loads.
cat > ${ANCHOR_FILE} <<'PF'
rdr pass on lo0 inet proto tcp from any to 127.0.0.1 port ${PANEL_LOCAL_HTTP_PORT} -> 127.0.0.1 port ${port}
PF

# 3. A LaunchDaemon that loads the anchor and enables pf at every boot, and once now.
cat > ${DAEMON} <<'PLIST'
${plist}
PLIST
chown root:wheel ${ANCHOR_FILE} ${DAEMON}
chmod 644 ${ANCHOR_FILE} ${DAEMON}
launchctl bootout system/${LABEL} 2>/dev/null || true
launchctl bootstrap system ${DAEMON}

${flush}
echo "installed: http://${PANEL_LOCAL_NAME} -> 127.0.0.1:${port}. Check it with: node bin/panel-local-name.mjs --check"
`;
}

export function renderUninstall() {
  return `${header(`Removes http://${PANEL_LOCAL_NAME}: the hosts block, the pf anchor and its LaunchDaemon.`)}
${dropHostsBlock}
launchctl bootout system/${LABEL} 2>/dev/null || true
pfctl -a ${ANCHOR} -F all 2>/dev/null || true
rm -f ${ANCHOR_FILE} ${DAEMON}
${flush}
echo "removed: ${PANEL_LOCAL_NAME}"
`;
}

const LOOPBACK = new Set(['127.0.0.1', '::1']);

function get(host, port, path) {
  return new Promise((resolve, reject) => {
    const req = request({ host, port, path, method: 'GET', timeout: 5_000 }, (res) => {
      let body = '';
      res.setEncoding('utf8');
      res.on('data', (d) => { body += d; });
      res.on('end', () => resolve({ status: res.statusCode, body }));
    });
    req.on('timeout', () => req.destroy(new Error('timed out')));
    req.on('error', reject);
    req.end();
  });
}

/** Where the chain from name to panel breaks, or null when it holds. Never needs root. */
export async function checkLocalName({ lookup = dnsLookup, fetch = get } = {}) {
  let addrs;
  try { addrs = await lookup(PANEL_LOCAL_NAME, { all: true }); }
  catch (e) { return `${PANEL_LOCAL_NAME} does not resolve (${e.code || e.message}): the hosts block is not installed`; }
  const off = addrs.map((a) => a.address).filter((a) => !LOOPBACK.has(a));
  if (off.length) return `${PANEL_LOCAL_NAME} resolves off loopback, to ${off.join(', ')}: something else answers for the name`;
  let r;
  try { r = await fetch(PANEL_LOCAL_NAME, PANEL_LOCAL_HTTP_PORT, '/api/csrf'); }
  catch (e) { return `port ${PANEL_LOCAL_HTTP_PORT} on ${PANEL_LOCAL_NAME} refused (${e.code || e.message}): the pf redirect is not loaded, or the panel is down`; }
  let token = null;
  try { token = JSON.parse(r.body).token; } catch { /* not the panel */ }
  if (r.status !== 200 || typeof token !== 'string') return `port ${PANEL_LOCAL_HTTP_PORT} answered ${r.status}, but not as the panel`;
  return null;
}

async function main(argv) {
  const write = argv.includes('--write');
  const check = argv.includes('--check');
  if (write === check) {
    console.error('usage: panel-local-name.mjs --write | --check');
    process.exit(2);
  }
  if (check) {
    const broken = await checkLocalName();
    if (broken) { console.log(`panel-local-name: ${broken}`); process.exit(1); }
    console.log(`panel-local-name: http://${PANEL_LOCAL_NAME} reaches the panel`);
    return;
  }
  const dir = outDir();
  try {
    writeAtomic(join(dir, 'install.sh'), renderInstall(operatorPort()), { mkdir: true });
    writeAtomic(join(dir, 'uninstall.sh'), renderUninstall(), { mkdir: true });
  } catch (e) {
    console.error(`panel-local-name: could not write ${dir}: ${e.message}`);
    process.exit(2);
  }
  console.log(`panel-local-name: wrote ${join(dir, 'install.sh')} and uninstall.sh`);
  console.log(`  read it, then: sudo sh ${join(dir, 'install.sh')}`);
}

if (isMainModule(import.meta.url)) main(process.argv.slice(2));
