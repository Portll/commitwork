#!/usr/bin/env node
// `gitleaks detect --no-git` consults no ignore rules, so the target's gitignored paths are
// allowlisted here. gitleaks 8.30.1 loads one `[extend] path` level and fails on a second, so this
// file extends the base and never a scope file.
//
// usage: node bin/gitleaks-scope-config.mjs <baseConfig> <outDir> [outName]
// exit: 0 the config to scan with is on stdout: the scope config, or the base config when git
//       cannot list the paths or the target has none · 1 the base config is unreadable, or the
//       scope config cannot be written; stdout is empty · 2 usage: a required argument is missing
import { accessSync, constants, mkdirSync, renameSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { scannedGit } from './lib/git-env.mjs';
import { isMainModule } from '../lib/is-main.mjs';

export const DESCRIPTION = 'gitignored paths (git ls-files --others --ignored --exclude-standard)';

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** The target's gitignored entries, or { error } when git cannot say (absent, not a repo, failed). */
export function ignoredEntries(cwd) {
  const r = scannedGit(cwd, ['ls-files', '--others', '--ignored', '--exclude-standard', '--directory', '-z'],
    { timeout: 120_000, maxBuffer: 64 << 20 });
  if (r.error || r.status !== 0) {
    const why = (r.error && r.error.message) || String(r.stderr || '').trim().split('\n')[0] || `git exited ${r.status}`;
    return { error: why };
  }
  return { entries: r.stdout.split('\0').filter(Boolean) };
}

// gitleaks matches the path relative to --source with `/` separators. A name that cannot sit in a
// TOML literal string is skipped and named rather than guessed at.
/** git's `--others --ignored --directory` entries → { regexes: ['^dir/', '^file$'], skipped }. */
export function ignoredToRegexes(entries) {
  const regexes = [], skipped = [];
  for (const e of entries) {
    const dir = /\/$/.test(e);
    const p = String(e).replace(/\/+$/, '');
    if (!p || p === '.') continue;
    if (/'''|[\n\r]/.test(p)) { skipped.push(e); continue; }
    regexes.push(dir ? `^${escapeRe(p)}/` : `^${escapeRe(p)}$`);
  }
  return { regexes, skipped };
}

const tomlString = (s) => (/['\n\r]/.test(s)
  ? `"${s.replace(/[\\"]/g, '\\$&').replace(/\n/g, '\\n').replace(/\r/g, '\\r')}"`
  : `'${s}'`);

/** The scope config's text: extends `base` (absolute), then one allowlist block for `regexes`. */
export function scopeConfigText(base, regexes) {
  return [
    '# Generated by bin/gitleaks-scope-config.mjs for one scan; never hand-edit.',
    '[extend]',
    `path = ${tomlString(base)}`,
    '',
    '[[allowlists]]',
    `description = "${DESCRIPTION}"`,
    'paths = [',
    ...regexes.map((r) => `  '''${r}''',`),
    ']',
    '',
  ].join('\n');
}

if (isMainModule(import.meta.url)) {
  const [baseArg, outDir, outName = 'gitleaks-scope.toml'] = process.argv.slice(2);
  const fail = (msg) => { process.stderr.write(`gitleaks-scope-config: ${msg}\n`); process.exitCode = 1; };
  if (!baseArg || !outDir) { process.stderr.write('usage: gitleaks-scope-config.mjs <baseConfig> <outDir> [outName]\n'); process.exitCode = 2; }
  else {
    const base = resolve(baseArg);
    let readable = true;
    try { accessSync(base, constants.R_OK); } catch (e) { readable = false; fail(`base config ${base} is not readable: ${e.code || e.message}`); }
    if (readable) {
      const ig = ignoredEntries(process.cwd());
      const say = (why) => process.stderr.write(`gitleaks-scope-config: gitignored paths NOT excluded (${why}); scanning with the base config, so gitignored files are in this scan\n`);
      if (ig.error) { say(ig.error); process.stdout.write(base + '\n'); }
      else {
        const { regexes, skipped } = ignoredToRegexes(ig.entries);
        for (const s of skipped) process.stderr.write(`gitleaks-scope-config: NOT excluded, the name cannot be stated in TOML: ${s}\n`);
        if (!regexes.length) { say('the target has no gitignored paths'); process.stdout.write(base + '\n'); }
        else {
          const out = join(resolve(outDir), outName);
          const tmp = `${out}.${process.pid}.tmp`;
          try {
            mkdirSync(resolve(outDir), { recursive: true });
            writeFileSync(tmp, scopeConfigText(base, regexes));
            renameSync(tmp, out);
            process.stderr.write(`gitleaks-scope-config: ${regexes.length} gitignored path(s) excluded via ${out}\n`);
            // exitCode, never process.exit(): a piped stdout is cut off by an exit before it drains
            process.stdout.write(out + '\n');
          } catch (e) { fail(`cannot write ${out}: ${e.code || e.message}`); }
        }
      }
    }
  }
}
