#!/usr/bin/env node
// bin/house-css.mjs — writes and checks generated copies of the house stylesheet (lib/house-css.mjs)
// for pages that link it rather than inline it: the panel's /static/house.css, and static pages that
// open from disk or ship to another host.
//
//   node bin/house-css.mjs --write [<path>] [--fonts served|inline|none] [--sans 400,600,italic] [--mono 400]
//   node bin/house-css.mjs --check [<path>...]
//
// With no path, both act on the registered copies (COPIES) with their registered options. A copy
// named on the command line is checked against the options its own header records. A copy that is an
// .html page is the content of its <style id="house-css"> block, for a page whose CSP admits inline
// style only; the page must carry that block, and everything outside it is left alone.
//
// env: CW_HOUSE_CSS_ROOT (the tree every registered copy is found in) · CW_ADMIN_STATIC (where
//      admin/static/house.css lives) · CW_WEB_ROOT · CW_FONTS_DIR (faces for --fonts inline)
// exit: 0 written, or every copy fresh · 1 a copy is stale or missing · 2 usage error, a header that
//       records no options, or a copy that cannot be read

import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { houseCss, FONT_MODES, selectFaces } from '../lib/house-css.mjs';
import { writeAtomic } from '../monitor/lockfile.mjs';
import { isMainModule } from '../lib/is-main.mjs';

const CW = join(dirname(fileURLToPath(import.meta.url)), '..');
const houseRoot = () => process.env.CW_HOUSE_CSS_ROOT || CW;
const adminStatic = () => process.env.CW_ADMIN_STATIC || join(houseRoot(), 'admin', 'static');

export const COPIES = Object.freeze([
  { name: 'panel', path: () => join(adminStatic(), 'house.css'), opts: { fonts: 'served' } },
  { name: 'landing', path: () => join(houseRoot(), 'admin', 'public', 'index.html'), opts: { fonts: 'none' } },
  { name: 'mainline', path: () => join(houseRoot(), 'sitemap', 'mainline.html'), opts: { fonts: 'none' } },
  { name: 'sitemap', path: () => join(houseRoot(), 'sitemap', 'demo.html'), opts: { fonts: 'none' } },
]);

const REGION_OPEN = '<style id="house-css">';
const isPage = (path) => /\.html?$/i.test(path);

// The copy a file carries: the whole file, or the house-css block of a page. null when a page has no
// block to hold one.
function extract(path, text) {
  if (!isPage(path)) return text;
  const at = text.indexOf(REGION_OPEN);
  if (at < 0) return null;
  const end = text.indexOf('</style>', at);
  return end < 0 ? null : text.slice(at + REGION_OPEN.length, end);
}

function embed(path, text, copy) {
  if (!isPage(path)) return copy;
  const at = text.indexOf(REGION_OPEN);
  const end = at < 0 ? -1 : text.indexOf('</style>', at);
  if (end < 0) throw new Error(`${path} has no ${REGION_OPEN}</style> block to hold the copy`);
  return text.slice(0, at + REGION_OPEN.length) + copy + text.slice(end);
}

const FAMILIES = ['sans', 'mono'];

const optionString = ({ fonts = 'served', weights } = {}) => [`fonts=${fonts}`,
  ...(weights ? FAMILIES.filter((k) => k in weights).map((k) => `${k}=${weights[k].join(',')}`) : [])].join(' ');

const HEADER_RE = /^\/\* Generated by bin\/house-css\.mjs \(([^)]*)\) from lib\/house-css\.mjs\b/;

export function renderCopy(opts = {}) {
  return `/* Generated by bin/house-css.mjs (${optionString(opts)}) from lib/house-css.mjs; `
    + `regenerate with node bin/house-css.mjs --write, never hand-edit. */\n${houseCss(opts)}\n`;
}

const parseWeights = (list) => (list === '' ? [] : list.split(',').map((w) => (w === 'italic' ? w : /^\d+$/.test(w) ? Number(w) : w)));

function validate(opts) {
  if (!FONT_MODES.includes(opts.fonts)) throw new RangeError(`fonts must be one of ${FONT_MODES.join(', ')} (got ${opts.fonts})`);
  selectFaces(opts.weights);
  return opts;
}

export function parseHeader(text) {
  const m = HEADER_RE.exec(text);
  if (!m) return null;
  const opts = { fonts: null };
  for (const pair of m[1].split(' ').filter(Boolean)) {
    const eq = pair.indexOf('=');
    const [k, v] = eq < 0 ? [pair, null] : [pair.slice(0, eq), pair.slice(eq + 1)];
    if (k === 'fonts' && v) opts.fonts = v;
    else if (FAMILIES.includes(k) && v !== null) (opts.weights ||= {})[k] = parseWeights(v);
    else return null;
  }
  try { return validate(opts); } catch { return null; }
}

const USAGE = `usage: node bin/house-css.mjs --write [<path>] [--fonts served|inline|none] [--sans <list>] [--mono <list>]
       node bin/house-css.mjs --check [<path>...]

Writes or checks a generated copy of lib/house-css.mjs's houseCss(). With no path, both act on the
registered copies (${COPIES.map((c) => c.name).join(', ')}). --sans and --mono take a comma list of
weights (sans: 400,500,600,700,italic · mono: 400,600,700); naming either ships only those faces.
`;

function readCopy(path) {
  try { return readFileSync(path, 'utf8'); } catch (e) { if (e.code === 'ENOENT') return null; throw e; }
}

export function main(argv, out = process.stdout, err = process.stderr) {
  const args = [...argv];
  let mode = null;
  const paths = [];
  const opts = { fonts: undefined, weights: undefined };
  const usage = (msg) => { err.write(`house-css: ${msg}\n${USAGE}`); return 2; };
  while (args.length) {
    const a = args.shift();
    if (a === '--help' || a === '-h') { out.write(USAGE); return 0; }
    if (a === '--write' || a === '--check') {
      if (mode && mode !== a) return usage('--write and --check are exclusive');
      mode = a;
    } else if (a === '--fonts') {
      opts.fonts = args.shift();
      if (!opts.fonts) return usage('--fonts needs a value');
    } else if (a === '--sans' || a === '--mono') {
      const v = args.shift();
      if (v === undefined) return usage(`${a} needs a list`);
      (opts.weights ||= {})[a.slice(2)] = parseWeights(v);
    } else if (a.startsWith('-')) {
      return usage(`unknown option ${a}`);
    } else paths.push(a);
  }
  if (!mode) return usage('say --write or --check');
  const optioned = opts.fonts !== undefined || opts.weights !== undefined;

  if (mode === '--write') {
    if (paths.length > 1) return usage('--write takes one path');
    if (!paths.length && optioned) return usage('the registered copies carry their own options; name a path to set them');
    const targets = paths.length ? [{ path: resolve(paths[0]), opts: { ...opts, fonts: opts.fonts ?? 'served' } }]
      : COPIES.map((c) => ({ path: c.path(), opts: c.opts }));
    for (const t of targets) {
      try { validate(t.opts); } catch (e) { return usage(e.message); }
      let body;
      try {
        const current = isPage(t.path) ? readCopy(t.path) : '';
        if (current === null) throw new Error('the page does not exist');
        body = embed(t.path, current, renderCopy(t.opts));
      } catch (e) { err.write(`house-css: cannot render ${t.path}: ${e.message}\n`); return 2; }
      writeAtomic(t.path, body, { mkdir: true });
      out.write(`wrote  ${t.path}\n`);
    }
    return 0;
  }

  if (optioned) return usage('--check reads the options from each copy; it takes none');
  const targets = paths.length ? paths.map((p) => ({ path: resolve(p), opts: null }))
    : COPIES.map((c) => ({ path: c.path(), opts: c.opts }));
  let code = 0;
  for (const t of targets) {
    let text;
    try { text = readCopy(t.path); } catch (e) { err.write(`house-css: cannot read ${t.path}: ${e.code || e.message}\n`); return 2; }
    if (text === null) { out.write(`missing ${t.path}\n`); code = Math.max(code, 1); continue; }
    const copy = extract(t.path, text);
    if (copy === null) { err.write(`house-css: ${t.path} has no ${REGION_OPEN} block\n`); return 2; }
    const recorded = t.opts || parseHeader(copy);
    if (!recorded) { err.write(`house-css: ${t.path} carries no bin/house-css.mjs header, so there is nothing to regenerate it from\n`); return 2; }
    let want;
    try { want = renderCopy(recorded); } catch (e) { err.write(`house-css: cannot regenerate ${t.path}: ${e.message}\n`); return 2; }
    const fresh = copy === want;
    out.write(`${fresh ? 'fresh ' : 'stale '} ${t.path}\n`);
    if (!fresh) code = Math.max(code, 1);
  }
  if (code) err.write('house-css: regenerate with node bin/house-css.mjs --write [<path>]\n');
  return code;
}

if (isMainModule(import.meta.url)) {
  const code = main(process.argv.slice(2));
  if (code) process.exitCode = code;
}
