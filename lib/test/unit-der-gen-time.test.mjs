// Formats a date as a DER GeneralizedTime TLV (lib/der.mjs genTime).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { genTime } from '../der.mjs';

test('encodes a date with zero milliseconds as GeneralizedTime without fraction', () => {
  const input = new Date(Date.UTC(2024, 0, 1, 0, 0, 0, 0));
  const expected = Buffer.from([
    0x18, 0x0f,
    0x32, 0x30, 0x32, 0x34, 0x30, 0x31, 0x30, 0x31, 0x30, 0x30, 0x30, 0x30, 0x30, 0x30, 0x5a
  ]);
  assert.deepEqual(genTime(input), expected);
});

