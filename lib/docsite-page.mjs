// THE PUBLIC ORIGIN the generated pages name themselves by. A canonical URL and an og:url are
// ABSOLUTE by specification — a relative canonical is ignored and a relative og:image is not
// fetched by most crawlers — so the origin has to be baked into the bytes. Read at call time, so a
// test or a preview deployment can set it; the committed artifacts carry the default, which is the
// production host the launchlist probes (monitor/private/launchlist/config.json `site`).
export const siteBase = () => (process.env.CW_DOCSITE_BASE_URL || 'https://i.commitwork.online').replace(/\/+$/, '');

// The og:image. 1200x630 is not advice: X and LinkedIn crop anything else, and Slack falls back to
// a small-card layout. Produced by bin/docsite-og-image.mjs into docsite/public/, which
// bin/docsite-publish.mjs passes through to the bundle root — so the tag and the asset ship in one
// act. If the asset is ever removed, the TAG MUST GO WITH IT: an og:image naming a 404 is worse
// than no og:image, because a crawler that fetched it records the failure against the page.
// bin/docsite-publish.mjs refuses to publish when the tag is emitted and the file is absent.
export const OG_IMAGE = '/og.png';

// Head metadata, opt-in. Emitted only for the arguments it is GIVEN, which is what keeps every
// renderShellPage() caller (bin/taxonomy-render.mjs, bin/scanner-taxonomy-render.mjs,
// bin/remediation-web.mjs, bin/taxonomy-web.mjs) byte-identical to before this existed: they pass
// neither, so they get neither. og:* is all-or-nothing on purpose — a partial Open Graph card
// renders worse than none, so the three required tags are emitted together or not at all.
const headMeta = ({ description = '', canonicalPath = '', title = '', noindex = false }) => {
  const out = [];
  if (noindex) out.push('<meta name="robots" content="noindex">');
  if (description) out.push(`<meta name="description" content="${esc(description)}">`);
  const canonical = canonicalPath ? `${siteBase()}${canonicalPath}` : '';
  if (canonical) out.push(`<!-- nosemgrep: html.security.audit.missing-integrity.missing-integrity -- canonical is metadata and is never fetched --><link rel="canonical" href="${esc(canonical)}">`);
  // A page that asks not to be indexed advertises no share card either.
  if (description && canonical && !noindex) {
    out.push('<meta property="og:type" content="website">',
      '<meta property="og:site_name" content="commitwork docs">',
      `<meta property="og:title" content="${esc(title)}">`,
      `<meta property="og:description" content="${esc(description)}">`,
      `<meta property="og:url" content="${esc(canonical)}">`,
      `<meta property="og:image" content="${esc(siteBase() + OG_IMAGE)}">`,
      '<meta property="og:image:width" content="1200">',
      '<meta property="og:image:height" content="630">',
      '<meta name="twitter:card" content="summary_large_image">');
  }
  return out.length ? `\n${out.join('\n')}` : '';
};

