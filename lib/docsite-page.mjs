// A doc page. state !== 'published' renders an honest badge (hidden = reachable-not-listed by
// declaration; draft appears only in local preview since the publish bundle excludes it).
// The shell always renders its own <h1> from the manifest's declared title (the canonical
// identity, independent of whatever the source happens to say). Markdown content routinely
// opens with its own '# Title' line, which renderDocBody turns into a second, leading <h1> —
// measured live on the field guide page: two <h1>s back to back, one from each source. Stripped
// here, once, rather than asking every markdown source to omit its own title — a source that
// still opens with a real H1 (for its own readability as plain markdown, or when rendered
// somewhere other than this shell) keeps it; only the DUPLICATE that would appear on this page
// is dropped.
// THE shell, for the GENERATORS. bin/taxonomy-render.mjs, bin/scanner-taxonomy-render.mjs,
// bin/remediation-web.mjs and bin/taxonomy-web.mjs build their body HTML from JSON rather than
// Markdown, so they cannot go through renderPage() — but before this they each carried a private
// copy of the chrome instead, which is the divergence the write-cardinality rule at the top of
// this file exists to prevent. They are now callers, not implementations.
//
// `extraHead` lands AFTER <style>${CSS}</style>, so a generator's own rules override the shell's
// by ordinary cascade — that is where page-specific table CSS goes, and where a wide page puts its
// `@page{size:A4 landscape}` override. The shell's @media print block is the PDF renderer for
// every page that uses it; a generator overriding page SIZE keeps that renderer rather than
// replacing it, which is what let taxonomy-reference stop being self-styled without losing print.
//
// `generator` names the real producer in the line-2 never-hand-edit header, which docs-doctor and
// human readers both read. It defaults to bin/docsite-build.mjs, so every existing caller renders
// byte-identically to before this export existed.
export function renderShellPage(opts) { return shell(opts); }

const stripLeadingH1 = (html) => html.replace(/^\s*<h1[^>]*>[\s\S]*?<\/h1>\s*/, '');

// THE footer links every docsite page carries. Both are reachable from the bundle: /privacy/ is a
// manifest doc and the mailto needs no server. The contact address is the one LICENSING.md already
// publishes as the licensing contact — not a second address invented for the site, which would be
// an address nobody monitors.
export const SITE_LINKS = Object.freeze([
  Object.freeze({ href: '/privacy/', text: 'Privacy' }),
  Object.freeze({ href: '/licensing/', text: 'Licensing and contact' }),
]);

// A meta description, derived from the source rather than declared in the manifest. Declaring it
// would mean a fourth place to keep current and a page whose description silently predates its
// rewrite; derived, it cannot go stale against the text it summarises. Takes the first real
// paragraph: the manifest's title is already the <h1>, so a leading '# …' line is the duplicate the
// shell strips from the body and is dropped here for the same reason.
// Comments are removed until none remain: one pass over `<!-<!-- x -->- note -->` leaves a whole comment.
// This loop shape is the one CodeQL's incomplete-multi-character-sanitization query recognises.
const stripComments = (s) => { let next; while ((next = s.replace(/<!--[\s\S]*?-->/g, '')) !== s) s = next; return s; };

export function metaDescription(md, limit = 155) {
  const body = stripComments(String(md))
    .replace(/^\uFEFF/, '')
    .split(/\n{2,}/)
    .map((b) => b.trim())
    .find((b) => b && !b.startsWith('#') && !b.startsWith('>') && !b.startsWith('|') && !b.startsWith('```')) || '';
  const flat = body
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')      // links → their text
    .replace(/[*_`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (flat.length <= limit) return flat;
  // Cut on a word boundary. A description sliced mid-word is quoted mid-word in a search result.
  return `${flat.slice(0, flat.lastIndexOf(' ', limit - 1) > 0 ? flat.lastIndexOf(' ', limit - 1) : limit - 1)}…`;
}

export function renderPage({ doc, md, nav = [] }) {
  const srcHash = sha256Hex(md);
  const badge = doc.state === 'published' ? '' : `<span class="badge${doc.state === 'draft' ? ' warn' : ''}">${esc(doc.state)}</span>`;
  // A doc that is not published must not invite indexing of a URL the next publish may withdraw —
  // hidden means reachable-and-unlisted by declaration, and draft never leaves the local preview.
  return shell({
    title: doc.title,
    bodyHtml: stripLeadingH1(renderDocBody(md)),
    srcHash,
    nav,
    currentSlug: doc.slug,
    badge,
    description: metaDescription(md),
    canonicalPath: docHref(doc),
    noindex: doc.state !== 'published',
    siteLinks: SITE_LINKS,
  });
}

// The home page's description and social card text. This is the one string on the site that is not
// derived from a document, so it is the one that can drift from what commitwork is — it names the
// three things the tool does and the thing this site is, and nothing it cannot be held to.
export const INDEX_DESCRIPTION = 'Reference documents for commitwork: a repository security scanner, '
  + 'local CI runner and scheduled monitoring system, with remediation and compliance-evidence tooling.';

// The index. rows: [{title, href, state, freshness}] — freshness is one of fresh|stale|unknown|
// imported and is ALWAYS shown: an unknown renders as unknown, never as fresh (explicit uncertainty)
// and never as an alarm (explicit uncertainty).
export function renderIndex({ rows, note = '', showFreshness = false }) {
  const items = rows.map((r) => {
    // THE FRESHNESS SIGNAL IS OPT-IN, and both callers are deliberate. On the PUBLIC index it is
    // off (operator instruction 2026-08-29): it answers a build question — "is this HTML current
    // with its source" — that a reader cannot act on, and sitting beside the title it read as a
    // claim about the writing. In the panel's LOCAL DRAFTING VIEW it is the entire point, because
    // fresh/stale/unknown is what tells the operator a page needs rebuilding.
    // Defaulting it OFF and passing it explicitly is what makes that a decision each caller makes
    // rather than one the last edit happened to leave behind — the first version of this change
    // hid it everywhere and blinded the drafting view without failing anything.
    const fresh = r.label ? `<span class="fresh label">${esc(r.label)}</span>`
      : showFreshness
        ? (r.freshness === 'imported'
          ? '<span class="fresh unknown">imported snapshot</span>'
          : `<span class="fresh ${esc(r.freshness)}">${esc(r.freshness)}</span>`)
        : '';
    const badge = r.state && r.state !== 'published' ? `<span class="badge">${esc(r.state)}</span>` : '';
    return `<li><a href="${esc(r.href)}">${esc(r.title)}</a>${badge}${fresh}</li>`;
  }).join('\n');
  const bodyHtml = `${note ? `<p>${esc(note)}</p>` : ''}\n<ul class="doclist">\n${items}\n</ul>`;
  return shell({
    title: 'Documents',
    bodyHtml,
    srcHash: sha256Hex(rows.map((r) => `${r.href}\t${r.title}\t${r.state}\t${r.freshness}\t${r.label || ''}`).join('\n')),
    description: INDEX_DESCRIPTION,
    canonicalPath: '/',
    siteLinks: SITE_LINKS,
  });
}

// Cloudflare Pages serves index.html with a 200 for EVERY unmatched URL unless the bundle carries
// a root 404.html — so a hidden or deleted page reads as "still published" to anyone probing it,
// a soft green about content that does not exist. Measured on this project 2026-08-28: /guide/
// answered 200 with the index body after its draft was excluded from the deploy — the same defect
// commitwork-web had already fixed. This page's PRESENCE in the bundle is what flips Pages from
// SPA fallback to real 404s; its content is secondary.
export function render404() {
  const bodyHtml = '<p>No page lives at this address. It may have been unpublished, or never existed.</p>\n'
    + '<p><a href="/">The document index</a> lists everything published.</p>';
  // noindex and NO canonical: a 404 that names a canonical URL asks a crawler to index the address
  // that just failed. The description exists so the page is not a blank card when one is shared.
  return shell({
    title: 'Not found',
    bodyHtml,
    srcHash: sha256Hex('404'),
    description: 'No page lives at this address on the commitwork document site.',
    noindex: true,
    siteLinks: SITE_LINKS,
  });
}

// THE write path for a generated page — every writer of pages/<urlPath>/index.html calls this.
export function renderAndWritePage({ doc, md, outPath, nav = [] }) {
  const html = renderPage({ doc, md, nav });
  let previous = null;
  try { previous = readFileSync(outPath, 'utf8'); } catch { /* first render — nothing to snapshot */ }
  snapshotBeforeWrite(doc.urlPath, 'generated', previous, { root: rootOf(doc) });
  mkdirSync(dirname(outPath), { recursive: true });
  writeAtomic(outPath, html);
  return { html, srcHash: sha256Hex(md) };
}

