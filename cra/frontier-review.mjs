// cra/frontier-review.mjs — the human half of closing the taint frontier.
//
// cra/taint-frontier.mjs finds calls where untrusted data enters an external API and no taint route
// ends. Each one needs a decision only a reviewer can make: is the API a sink nobody modelled, a
// pass-through the engine loses taint in, or plumbing that never reaches anything dangerous? This
// module keeps those decisions and closes the loop:
//
//   draft    the sweep's unclaimed APIs are merged into a worksheet per repository, one entry per
//            language|api|argument. Never keyed on a line: a call that moves is the same question.
//            Decisions already made are kept, so a re-draft is idempotent.
//   decide   the reviewer sets each entry's `decision` (shape below).
//   emit     decided sink and summary rows become a CodeQL data-extension file that
//            bin/codeql-model-pack.mjs loads into the next CodeQL lane.
//   verify   applyReview reads the worksheet against a frontier: a neutral call is `reviewed`, not
//            unclaimed; a call decided a sink that is STILL unclaimed after a sweep is flagged, because
//            the model did not take (wrong row, or no query of that sink kind ran).
//
// WHY NEUTRAL LIVES HERE AND NOT IN CODEQL. In CodeQL 2.27.3's JavaScript library the frontier query
// excludes safe APIs through QL classes (SafeExternalApiPackage, SafeExternalApiFunction in
// ExternalAPIUsedWithUntrustedDataCustomizations.qll), not through data extensions, so no YAML can
// remove plumbing from the frontier. The reviewer's "this is plumbing" is recorded here instead.
//
// WHY THE REVIEWER WRITES THE ROW. A frontier API name (`jsr:@astral/astral@0.5.Page().evaluate()
// [callback 0 result]`) is the query's display name, not a model access path, and every language's
// model row has its own columns. A translation guessed here would emit models that silently do not
// match; the verify step would catch it a sweep later. So a sink decision carries the full model row
// the reviewer wrote, and this module only places it.
//
// Measured on one repository's database (2026-10-21): 7 frontier calls, 3 APIs, all unclaimed — 6 UI state
// hooks fed by the URL query (plumbing) and 1 headless-browser call in end-to-end test code.
//
// The worksheet lives beside the models in the private store, <models dir>/<repo>/frontier-review.json.
// bin/codeql-model-pack.mjs loads only *.yml from that directory, so the worksheet never enters a pack.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

export const REVIEW_FILE = 'frontier-review.json';
export const REVIEW_VERSION = 1;
export const reviewPath = (modelsDir, repo) => join(modelsDir, repo, REVIEW_FILE);
export const generatedModelFile = (lib) => `frontier-${lib}.yml`;
export const GENERATED_HEADER = '# Generated by cra/frontier-review.mjs from frontier-review.json. Regenerate with `node bin/frontier-review.mjs emit`; never hand-edit.';

const MAX_FILES = 20;
const MAX_TEXT = 400;
const byString = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** Identity of one review question: language, API, argument. NEVER the line or the file. */
export const reviewKey = (language, api, param) => [language, api, param || ''].join('|');

// A decision's shape. `as` decides what the entry becomes:
//   neutral  { as: 'neutral', why }                      plumbing: counted reviewed, emits nothing
//   sink     { as: 'sink', row: [...] }                   a sinkModel row, exactly as CodeQL takes it
//   summary  { as: 'summary', row: [...] }                a summaryModel row (taint passes through)
const EXTENSIBLE = Object.freeze({ sink: 'sinkModel', summary: 'summaryModel' });

/**
 * What a reviewer needs on the page to decide, written into every drafted worksheet: the three
 * choices, the exact shape each takes, and what each does downstream. The entries carry the rest —
 * where untrusted data comes from (`sources`) and every call site (`sites`), so a decision is made
 * against the code and not against an API name.
 */
export const DECISION_GUIDE = Object.freeze({
  question: 'Untrusted data reaches this library argument and no taint rule follows it further. What happens to it inside the library?',
  neutral: { shape: { as: 'neutral', why: '<why the value reaches nothing dangerous>' }, when: 'Plumbing: state, rendering as text, test code. Counted reviewed; emits no model.' },
  sink: { shape: { as: 'sink', row: ['<package>', '<access path>', '<sink kind>'] }, when: 'The library itself does something dangerous with the value. The row is the language\'s CodeQL sinkModel row as written; emit places it in the next CodeQL lane.' },
  summary: { shape: { as: 'summary', row: ['<package>', '<access path in>', '<access path out>', 'taint'] }, when: 'The library hands the value back (a return or a callback) and taint should continue there. The row is a CodeQL summaryModel row.' },
  undecided: { shape: null, when: 'Leave decision null. The call stays open in the frontier count.' },
});

/** -> { ok: true, as } | { ok: false, reason }. null is undecided and valid. */
export function validateDecision(d) {
  if (d === null || d === undefined) return { ok: true, as: null };
  if (typeof d !== 'object' || Array.isArray(d)) return { ok: false, reason: 'a decision is an object or null' };
  if (d.as === 'neutral') {
    return typeof d.why === 'string' && d.why.trim() ? { ok: true, as: 'neutral' } : { ok: false, reason: 'a neutral decision states why the call reaches nothing dangerous' };
  }
  if (d.as in EXTENSIBLE) {
    const row = d.row;
    if (!Array.isArray(row) || row.length < 2 || !row.every((c) => typeof c === 'string' && c.length && c.length <= MAX_TEXT)) {
      return { ok: false, reason: `a ${d.as} decision carries its model row: two or more non-empty strings, as the language's ${EXTENSIBLE[d.as]} takes them` };
    }
    return { ok: true, as: d.as };
  }
  return { ok: false, reason: `unknown decision ${JSON.stringify(String(d.as)).slice(0, 60)}: one of neutral, sink, summary` };
}

/**
 * Read a worksheet. Fails closed: only ENOENT is `absent`; a file that cannot be read or parsed, or
 * has the wrong shape, is never an empty worksheet — a draft over it would discard the decisions.
 * -> { state: 'ok'|'absent'|'unreadable'|'unparseable'|'invalid', reason, review }
 */
export function readReview(path) {
  let raw;
  try { raw = readFileSync(path, 'utf8'); } catch (e) {
    if (e && e.code === 'ENOENT') return { state: 'absent', reason: null, review: null };
    return { state: 'unreadable', reason: `${path}: ${(e && e.code) || 'unknown error'}`, review: null };
  }
  let j;
  try { j = JSON.parse(raw); } catch { return { state: 'unparseable', reason: `${path}: not valid JSON`, review: null }; }
  if (!j || typeof j !== 'object' || j.v !== REVIEW_VERSION || !Array.isArray(j.entries)) {
    return { state: 'invalid', reason: `${path}: not a version-${REVIEW_VERSION} worksheet with entries[]`, review: null };
  }
  for (const e of j.entries) {
    if (!e || typeof e.language !== 'string' || typeof e.api !== 'string') {
      return { state: 'invalid', reason: `${path}: an entry has no language or api`, review: null };
    }
  }
  return { state: 'ok', reason: null, review: j };
}

/**
 * Merge one sweep's frontier calls for a repository into its worksheet. Only UNCLAIMED calls with a
 * parsed API ask a question; a claimed call is already a finding. An entry the sweep did not see is
 * kept as it was, decision and all; a seen one has its counts and files refreshed. `source` is the
 * sweep's own name, so a re-draft of the same sweep writes the same bytes.
 */
export function mergeReview(review, repo, calls, source) {
  const prev = new Map((review ? review.entries : []).map((e) => [reviewKey(e.language, e.api, e.param), e]));
  const seen = new Map();
  for (const c of calls || []) {
    if (c.claimed || !c.api) continue;
    const k = reviewKey(c.language, c.api, c.param);
    const s = seen.get(k) || { language: c.language, api: c.api, param: c.param || null, calls: 0, files: new Set(), sources: new Set(), sites: new Map() };
    s.calls++;
    if (c.file) s.files.add(c.file);
    if (c.source) s.sources.add(c.source);
    // A site is evidence for the reviewer, never the entry's identity: it is refreshed every sweep.
    if (c.file) {
      s.sites.set(`${c.file}|${c.line ?? ''}`, {
        file: c.file, line: Number.isInteger(c.line) ? c.line : null,
        // where the untrusted value this call receives comes from: the other line to read
        from: c.sourceAt ? { file: c.sourceAt.file, line: c.sourceAt.line, label: c.source || null } : null,
      });
    }
    seen.set(k, s);
  }
  const out = new Map(prev);
  for (const [k, s] of seen) {
    const had = prev.get(k);
    const sites = [...s.sites.values()].sort((a, b) => byString(a.file, b.file) || (a.line ?? 0) - (b.line ?? 0));
    out.set(k, {
      language: s.language, api: s.api, param: s.param,
      calls: s.calls, files: [...s.files].sort(byString).slice(0, MAX_FILES), filesCut: s.files.size > MAX_FILES ? s.files.size : null,
      sources: [...s.sources].sort(byString).slice(0, MAX_FILES),
      sites: sites.slice(0, MAX_FILES), sitesCut: sites.length > MAX_FILES ? sites.length : null,
      firstSeen: had ? had.firstSeen : source, lastSeen: source,
      decision: had ? (had.decision ?? null) : null,
    });
  }
  const entries = [...out.entries()].sort(([a], [b]) => byString(a, b)).map(([, e]) => e);
  return { v: REVIEW_VERSION, repo, guide: DECISION_GUIDE, entries };
}

/** The worksheet as written: two-space JSON and a final newline, so a diff of a decision is one line. */
export const reviewText = (review) => `${JSON.stringify(review, null, 2)}\n`;

/**
 * The data-extension file for one library pack from a worksheet's decided rows, or null when no row
 * is decided for it. `language` is the frontier language; `lib` the pack's library name
 * (bin/codeql-model-pack.mjs LIBRARY). Rows are JSON arrays, which YAML reads as flow sequences.
 * -> { text, rows, invalid: [{ key, reason }] } | null
 */
export function modelsYaml(review, lib, languagesOfLib) {
  const groups = { sink: [], summary: [] };
  const invalid = [];
  for (const e of review.entries) {
    if (!languagesOfLib.includes(e.language)) continue;
    const v = validateDecision(e.decision);
    if (!v.ok) { invalid.push({ key: reviewKey(e.language, e.api, e.param), reason: v.reason }); continue; }
    if (v.as in groups) groups[v.as].push(JSON.stringify(e.decision.row));
  }
  const blocks = [];
  let rows = 0;
  for (const as of Object.keys(groups)) {
    const uniq = [...new Set(groups[as])].sort(byString);
    if (!uniq.length) continue;
    rows += uniq.length;
    blocks.push(`  - addsTo:\n      pack: codeql/${lib}-all\n      extensible: ${EXTENSIBLE[as]}\n    data:\n${uniq.map((r) => `      - ${r}`).join('\n')}`);
  }
  if (!rows) return invalid.length ? { text: null, rows: 0, invalid } : null;
  return { text: `${GENERATED_HEADER}\nextensions:\n${blocks.join('\n')}\n`, rows, invalid };
}

/**
 * A frontier (buildFrontier's result) with each repository's worksheet applied. `reviews` maps repo ->
 * readReview's result. Every unclaimed call gets `review`:
 *   'neutral'      decided plumbing: no longer open
 *   'sink-open'    decided a sink or summary, yet still unclaimed — the model did not take
 *   'invalid'      the decision does not validate: still open, and named
 *   'undecided'    no decision yet: open
 *   'unreviewed'   the repository's worksheet is absent: open
 *   'review-<state>' the worksheet could not be used (unreadable / unparseable / invalid): open
 * and the totals gain { open, neutral, sinkOpen, invalid }. `open` is what the frontier still asks.
 */
export function applyReview(frontier, reviews) {
  const totals = { ...frontier.totals, open: 0, neutral: 0, sinkOpen: 0, invalid: 0 };
  const repos = {};
  for (const [repo, r] of Object.entries(frontier.repos || {})) {
    const got = reviews[repo] || { state: 'absent' };
    const decisions = new Map(got.state === 'ok' ? got.review.entries.map((e) => [reviewKey(e.language, e.api, e.param), e.decision]) : []);
    const calls = r.calls.map((c) => {
      if (c.claimed) return c;
      let review;
      if (got.state === 'absent') review = 'unreviewed';
      else if (got.state !== 'ok') review = `review-${got.state}`;
      else if (!c.api) review = 'undecided';
      else {
        const d = decisions.get(reviewKey(c.language, c.api, c.param));
        const v = validateDecision(d);
        review = !v.ok ? 'invalid' : v.as === 'neutral' ? 'neutral' : v.as ? 'sink-open' : 'undecided';
      }
      if (review === 'neutral') totals.neutral++; else totals.open++;
      if (review === 'sink-open') totals.sinkOpen++;
      if (review === 'invalid') totals.invalid++;
      return { ...c, review };
    });
    repos[repo] = { ...r, calls, review: { state: got.state, ...(got.reason ? { reason: got.reason } : {}) } };
  }
  return { ...frontier, repos, totals };
}
